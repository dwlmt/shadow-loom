def _resolve_pov_policy(
    target_entities: Optional[List[str]],
    *,
    explicit_policy: Optional[str] = None,
) -> tuple[Optional[str], List[str], Literal["single", "rotating", "ensemble"]]:
    """Pick a POV lock + roster + policy from a brief's target entities.

    Returns ``(pov_lock, additional_pov_locks, pov_policy)``.

    Behaviour:

    * No targets → ``(None, [], "single")``.
    * Single target → ``(only, [], "single")``.
    * Multiple targets → ``(first, rest, explicit_policy or "rotating")``.

    Default multi-ego policy is ``"rotating"`` because the assembler
    typically returns concrete POV-able entities (no abstract narrator
    egos like ``ENT_AUDIENCE``); each gets its own beat. Callers that
    want omniscient-constrained interiority can pass
    ``explicit_policy='ensemble'``.

    A common case is a focus list that mixes the queried entity with
    ``ENT_AUDIENCE`` (the implicit reader-stand-in used during
    extraction). ``ENT_AUDIENCE`` is filtered from the POV roster so
    the prose isn't asked to render the audience's interiority, while
    still being kept on ``brief.target_entities`` for downstream
    assembly metrics.
    """
    if not target_entities:
        return None, [], "single"
    # Drop the audience pseudo-ego from POV licensing — it is never a
    # POV character — but keep the rest of the roster.
    real = [
        e for e in target_entities
        if e and e != "ENT_AUDIENCE"
    ]
    if not real:
        return None, [], "single"
    if len(real) == 1:
        return real[0], [], "single"
    policy_value: Literal["single", "rotating", "ensemble"]
    if explicit_policy in ("single", "rotating", "ensemble"):
        policy_value = explicit_policy  # type: ignore[assignment]
    else:
        policy_value = "rotating"
    if policy_value == "single":
        return real[0], [], "single"
    return real[0], real[1:], policy_value


def _entities_from_intervention_keys(
    intervention_keys: Iterable[str],
    world_state: WorldStateV1,
) -> List[str]:
    """Resolve an ``interventions`` dict's keys to a deduplicated list of
    entity IDs.

    Intervention keys may target entities directly (``ENT_KEN.fear``) or
    events (``EVT_KEN_KILLS_DOGS.outcome``).  For the event case we
    expand to the event's actors and targets so the rendered brief
    knows which entities the alternate timeline is about — without
    these the prompt logs ``entities=[]`` and downstream prompt
    sections that key off ``brief.target_entities`` (POV selection,
    auditor focus, etc.) get nothing to work with.
    """
    events_by_id = {e.id: e for e in getattr(world_state, "events", []) or []}
    seen: List[str] = []
    seen_set: set[str] = set()

    def _add(eid: str) -> None:
        if eid and eid.startswith("ENT_") and eid not in seen_set:
            seen_set.add(eid)
            seen.append(eid)

    for key in intervention_keys:
        node_id = key.split(".", 1)[0]
        if node_id.startswith("ENT_"):
            _add(node_id)
        elif node_id.startswith("EVT_") and node_id in events_by_id:
            evt = events_by_id[node_id]
            for aid in getattr(evt, "actor_ids", []) or []:
                _add(aid)
            for tid in getattr(evt, "target_ids", []) or []:
                _add(tid)
    return seen


def _syuzhet_to_fabula_anchor(
    world_state: WorldStateV1, syuzhet_anchor: Optional[int],
) -> Optional[int]:
    """Translate ``syuzhet_anchor`` → ``fabula_anchor``.

    Used by :func:`build_object_coherence_constraints` (and any other
    builder that needs to walk an object / entity / world-trait
    state_timeline) so per-tick reconstructed positions reflect what
    the reader has seen up to ``syuzhet_anchor``. Returns the maximum
    ``fabula_time`` of any event whose ``syuzhet_index`` is at or
    before the cap; ``None`` propagates when no anchor is supplied.
    """
    if syuzhet_anchor is None:
        return None
    fabula_anchor: Optional[int] = None
    for evt in getattr(world_state, "events", []) or []:
        if evt.syuzhet_index <= syuzhet_anchor and (
            fabula_anchor is None or evt.fabula_time > fabula_anchor
        ):
            fabula_anchor = evt.fabula_time
    return fabula_anchor


def _user_intent_constraints(original_query: Optional[str]) -> List[ConstraintBlock]:
    """Lift the user's verbatim NL request into a HARD constraint.

    Mirrors the equivalent block at the top of
    ``DirectiveAssembler.assemble`` so non-directive briefs (observation,
    intervention, counterfactual, evaluation fallback) also bind the
    rendering and audit prompts to the user's actual ask. Returns an
    empty list when no original query is available so callers can
    splat it unconditionally.
    """
    text = (original_query or "").strip()
    if not text:
        return []
    return [ConstraintBlock(
        constraint_type="narrative",
        priority="hard",
        instruction=(
            f"[USER INTENT \u2014 verbatim]: {text}\n"
            "The rendered scene MUST address the user's request above. "
            "Engine-derived constraints below are guard-rails, not "
            "substitutes for the user's intent."
        ),
        evidence={"original_query": text},
    )]


def build_observation_brief(
    query: ObservationQuery,
    physics_state: Dict[str, Any],
    world_state: WorldStateV1,
    *,
    preceding_prose: Optional[str] = None,
    branch_world_id: Literal["factual", "shadow"] = "factual",
    branch_label: Optional[str] = None,
    factual_contrast_summary: Optional[str] = None,
    syuzhet_anchor: Optional[int] = None,
    skipped_interventions: Optional[List[Dict[str, Any]]] = None,
) -> CreativeBrief:
    """Build a lightweight CreativeBrief for observation queries."""
    pov, extra_povs, pov_policy = _resolve_pov_policy(
        query.focus_entity_ids,
    )
    constraints: List[ConstraintBlock] = _user_intent_constraints(query.original_query)
    # Scene-internal grounding constraint (mirrors the counterfactual
    # rung). Without this the rung-1 prose is free to drift into
    # author-voice meta framing because the rendering directive's
    # ``stylistic_instructions`` are advisory; the constraint block
    # makes scenic grounding HARD across every prose-generating rung
    # so the auditor's stylistic checks have something concrete to bind
    # to and the ``narrative_style`` block is not the only style anchor.
    constraints.append(ConstraintBlock(
        constraint_type="narrative",
        priority="hard",
        instruction=(
            "Render this scene as the actual lived world \u2014 concrete "
            "physical action, sensory detail, and character behaviour, "
            "in plain past-tense narration. Do NOT use author-voice "
            "conditional or subjunctive framing (\"if he had\u2026\", "
            "\"would have\u2026\"). The events of this scene are what "
            "actually happened in this world."
        ),
        evidence={},
    ))
    # Negative-physics record: events the world tags as not occurring
    # and propositions committed FALSE at or before the anchor must
    # NOT be staged as having happened. Applies to every rung.
    constraints.extend(_build_skipped_intervention_constraints(
        skipped_interventions,
    ))
    constraints.extend(build_prevented_event_constraints(
        world_state, syuzhet_anchor, world_label="observed",
    ))
    constraints.extend(build_false_proposition_constraints(
        world_state, syuzhet_anchor, world_label="observed",
    ))
    constraints.extend(build_unrealised_concern_constraints(
        world_state, syuzhet_anchor, world_label="observed",
    ))
    constraints.extend(build_false_belief_grounding_constraints(
        world_state, syuzhet_anchor, world_label="observed",
    ))
    constraints.extend(build_object_coherence_constraints(
        world_state,
        _syuzhet_to_fabula_anchor(world_state, syuzhet_anchor),
        world_label="observed",
    ))
    # Anchor-event co-presence pin. When the observation query carries
    # ``anchor_after_event_id`` AND the resolved event has an
    # ``at_location_id``, the focus entities are watching / reacting
    # to that event — so the scene must be staged AT the event's
    # location, not at each focus entity's drifted last-known
    # location_id. Without this pin the renderer reconstructs each
    # focus entity at their stale ``EntityStateSnapshot.location_id``
    # (e.g. their home / flat) and then invents a remote channel to
    # bridge them to the trial / courtroom, missing the goal of the
    # query (witness the event live).
    constraints.extend(_build_anchor_event_copresence_constraints(
        query, world_state,
    ))
    scene_context = dict(physics_state) if isinstance(physics_state, dict) else {}
    if syuzhet_anchor is not None and isinstance(scene_context, dict):
        scene_context.setdefault("syuzhet_anchor", syuzhet_anchor)
    return CreativeBrief(
        target_effect="observation",
        target_entities=query.focus_entity_ids,
        original_query=query.original_query,
        constraints=constraints,
        narrative_style=getattr(world_state, "narrative_style", None),
        preceding_prose=preceding_prose,
        branch_world_id=branch_world_id,
        branch_label=branch_label,
        factual_contrast_summary=factual_contrast_summary,
        # Carry the withheld-information set so the renderer/auditor
        # see the same ``HIDDEN CHANNELS / UTTERANCES (HARD)`` block
        # the directive path enforces. Without this an observation at
        # an early syuzhet_anchor can leak the content of a future
        # utterance via the Rule-1 prose pathway.
        hidden_channels=compute_hidden_channels_for(
            world_state, syuzhet_anchor,
        ),
        rendering=RenderingDirective(
            rendering_mode="observation",
            pov_lock=pov,
            additional_pov_locks=extra_povs,
            pov_policy=pov_policy,
            pacing="normal",
            sensory_focus="wide",
            stylistic_instructions=[
                "Ground the prose in concrete physical reality \u2014 what "
                "the POV character sees, hears, touches, and does, "
                "moment by moment.",
                "Render the scene from the focal character's perspective.",
                "Describe what they see, hear, and feel in this moment.",
                "Include environmental details that set the tone.",
                "Ground the prose in the character's current emotional state (use trait values).",
                "Do NOT reveal information the focal character cannot perceive.",
                "Render the scene as the lived present of this world. Do "
                "not stand outside it as a narrator commenting on its "
                "structure.",
            ],
        ),
        scene_context=scene_context,
    )


def _build_anchor_event_copresence_constraints(
    query: Any,
    world_state: WorldStateV1,
) -> List[ConstraintBlock]:
    """Pin focus entities to the anchor event's ``at_location_id``.

    Fires when the query carries ``anchor_after_event_id`` AND the
    resolved event has an ``at_location_id``. Emits a HARD spatial
    constraint instructing the renderer to stage the scene at the
    event's location with every focus entity bodily present (rather
    than reconstructing each entity at their last
    ``EntityStateSnapshot.location_id``, which is often a stale
    home/flat that the renderer then bridges to the event via an
    invented channel).

    Returns ``[]`` when the query does not name an anchor event, when
    the event is missing from the world, or when the event has no
    ``at_location_id`` (no location to pin to).
    """
    after_id = getattr(query, "anchor_after_event_id", None)
    focus = list(getattr(query, "focus_entity_ids", None) or [])
    if not after_id or not focus:
        return []
    evt = next(
        (e for e in (world_state.events or []) if e.id == after_id), None,
    )
    if evt is None:
        return []
    loc_id = getattr(evt, "at_location_id", None)
    if not loc_id:
        return []
    loc = (world_state.locations or {}).get(loc_id)
    loc_name = getattr(loc, "name", None) or loc_id
    evt_desc = (getattr(evt, "description", None) or evt.id).strip().replace("\n", " ")
    if len(evt_desc) > 120:
        evt_desc = evt_desc[:117] + "\u2026"
    focus_str = ", ".join(f"`{eid}`" for eid in focus)
    return [ConstraintBlock(
        constraint_type="spatial",
        priority="hard",
        instruction=(
            f"ANCHOR-EVENT CO-PRESENCE: this observation is anchored "
            f"to `{evt.id}` (\u201c{evt_desc}\u201d), which takes place "
            f"at `{loc_id}` ({loc_name}). Stage the scene AT that "
            f"location with the focus entities ({focus_str}) bodily "
            f"present and witnessing the event live \u2014 do NOT "
            f"render them at their last-known home/flat with the "
            f"event reaching them through an invented "
            f"telephone/television/radio channel. If a focus entity "
            f"is canonically elsewhere at this fabula tick AND the "
            f"event has a declared `via_channel_id`, render the "
            f"reception as channel-mediated; otherwise place every "
            f"focus entity in the room with the event."
        ),
        evidence={
            "anchor_event_id": evt.id,
            "at_location_id": loc_id,
            "focus_entity_ids": focus,
            "fabula_time": getattr(evt, "fabula_time", None),
        },
    )]


def _build_skipped_intervention_constraints(
    skipped: Optional[List[Dict[str, Any]]],
) -> List[ConstraintBlock]:
    """Build HARD ConstraintBlocks listing intervention targets the
    engine could NOT apply.

    The engine records skips when a do-target names a node that is
    absent from the sandbox (and was not pre-declared via
    ``query.introduce`` or an ``<ID>.spawn`` surgery). Without this
    block the renderer would happily describe the intended state
    change as if it had taken effect, and the auditor would have no
    way to distinguish "the engine refused" from "the renderer
    forgot". Surfacing the ledger means the renderer is told NOT to
    depict the requested change and the auditor can flag prose that
    pretends it did.
    """
    if not skipped:
        return []
    lines: List[str] = []
    for entry in skipped:
        if not isinstance(entry, dict):
            continue
        target = entry.get("target_path") or entry.get("node_id") or "?"
        reason = entry.get("reason") or "unknown_node"
        detail = entry.get("detail") or ""
        lines.append(f"  \u2022 {target} \u2014 {reason}: {detail}".rstrip(":\u2014 "))
    if not lines:
        return []
    return [ConstraintBlock(
        constraint_type="mathematical",
        priority="hard",
        instruction=(
            "ENGINE-SIDE INTERVENTION SKIPS: the requested do-surgery "
            "targets below were NOT applied because their named nodes "
            "are absent from the world model. Render the scene as if "
            "those changes never took effect \u2014 do NOT depict the "
            "intended outcome, do NOT name the missing nodes as if "
            "they exist, and do NOT manufacture a substitute. If one "
            "of these targets was meant to be a new element, declare "
            "it under ``introduced_elements`` instead.\n"
            + "\n".join(lines)
        ),
        evidence={"skipped_interventions": skipped},
    )]


def _build_inert_intervention_constraints(
    *,
    intervention_inert: bool,
    intervention_inert_reason: Optional[str],
    rung_label: str,
    world_label: str,
) -> List[ConstraintBlock]:
    """HARD disclosure when the engine produced ZERO downstream effects.

    Companion to ``_build_cascade_exclusion_constraints`` and
    ``_build_skipped_intervention_constraints``. When the
    :class:`CausalPhysicsEngine` flags ``intervention_inert=True`` every
    requested do-target was Rule-3 pruned and/or every downstream
    propagation was absorbed by inertia / cyclic SCC. Without this
    block the renderer still receives the surgery as a "real" event
    and fabricates psychologically plausible aftermath ("calm held
    steady\u2026 professionalism remained unshaken\u2026") that the
    auditor then has to police as miracle steps. Emit a single
    pink-elephant-safe instruction telling the renderer to stage the
    *attempted* surgery and its *resistance* only \u2014 no downstream.
    """
    if not intervention_inert:
        return []
    reason = intervention_inert_reason or "no actionable downstream propagation"
    return [ConstraintBlock(
        constraint_type="mathematical",
        priority="hard",
        instruction=(
            f"=== INERT INTERVENTION (HARD) === \u2014 the {rung_label} "
            f"surgery in the {world_label} sandbox produced ZERO "
            f"downstream effects: {reason}. The do-operator either "
            f"failed to land or was fully absorbed by inertia / "
            f"cyclic SCC / affordance gate. Stage the *attempt* and "
            f"its *resistance* only \u2014 do NOT depict any trait "
            f"shift, relationship update, belief change, concern "
            f"flip, proposition flip, or world-state delta as a "
            f"consequence of this surgery. Any aftermath beat that "
            f"reads as 'the change took hold' (even subtly: 'still "
            f"steady\u2026', 'as composed as ever\u2026', 'unshaken') "
            f"is a miracle the auditor flags."
        ),
        evidence={
            "intervention_inert": True,
            "intervention_inert_reason": reason,
        },
    )]


def _build_cascade_exclusion_constraints(
    *,
    blocked: Optional[List[Dict[str, Any]]],
    rule3_pruned_interventions: Optional[List[str]],
    mutations: Optional[List[Dict[str, Any]]] = None,
    social_mutations: Optional[List[Dict[str, Any]]] = None,
    proposition_mutations: Optional[List[Dict[str, Any]]] = None,
    belief_mutations: Optional[List[Dict[str, Any]]] = None,
    concern_mutations: Optional[List[Dict[str, Any]]] = None,
    rule3_pruning_mode: Literal["advisory", "prune"] = "advisory",
    world_label: str,
    rung_label: str,
) -> List[ConstraintBlock]:
    """HARD pink-elephant EXCLUSIONS bounding the rendered cascade.

    The complementary half of :func:`_emit_downstream_cascade_lines`
    (which tells the renderer *what to render*). Three forbidden
    categories, all rendered pink-elephant-safe \u2014 we name the
    forbidden category by structural fingerprint (node + trait, edge
    endpoints, ids) so the renderer knows which beat is off-limits
    without being primed with the canonical phrasing of the forbidden
    content.

    Categories:

    * **Cascade-bounded miracle prevention** \u2014 the engine's
      propagation log is authoritative. Any downstream consequence
      *not* enumerated in the cascade payload would be a miracle step
      the auditor flags. We assert the bound rather than re-quote the
      cascade (the cascade lines are emitted separately by the
      ``intervention_branch`` / ``counterfactual_branch`` formatter,
      and re-quoting them here would just bloat the prompt).
    * **Blocked propagations** \u2014 the engine confirmed these targets
      *resisted* the cascade. Naming the would-have-been new state in
      the prose would silently undo the engine's verdict. We list
      ``node.trait blocked by reason`` only \u2014 never the would-be
      target value \u2014 so the renderer cannot pattern-match on the
      blocked outcome.
    * **Rule-3 pruned interventions** (counterfactual / intervention
      pre-flight) \u2014 these surgeries are provably vacuous against
      the user's query targets. The local clamp holds at the target
      node, but the rest of the world is unchanged: no downstream
      consequence may be invented for them. Advisory-mode pruning
      surfaces the same list but as soft warning.
    """
    blocks: List[ConstraintBlock] = []

    # 1. Cascade-bounded miracle prevention. Always emit when the
    # engine produced any cascade at all (otherwise the renderer has
    # no concrete cascade to bound against and the rule is vacuous).
    # ALSO emit when no cascade fired but the engine has blocked
    # propagations: in that case the bound is "zero downstream
    # effects" \u2014 the renderer needs an explicit ceiling so it does
    # not invent consequences to fill the blocked-but-staged void.
    cascade_present = bool(
        mutations or social_mutations or proposition_mutations
        or belief_mutations or concern_mutations
    )
    blocked_only = bool(blocked) and not cascade_present
    if cascade_present or blocked_only:
        n_total = sum(len(x or []) for x in (
            mutations, social_mutations, proposition_mutations,
            belief_mutations, concern_mutations,
        ))
        if blocked_only:
            _instr = (
                f"=== CASCADE-BOUNDED CONSEQUENCES (HARD) === \u2014 the "
                f"{rung_label} surgery propagated ZERO downstream "
                f"effects in the {world_label} sandbox \u2014 every "
                f"candidate propagation was absorbed by inertia, "
                f"cyclic SCC, or affordance gate (see BLOCKED "
                f"PROPAGATIONS below for the full resistance list). "
                f"The cascade bound is therefore ZERO: do NOT invent "
                f"ANY downstream trait shift, relationship update, "
                f"belief change, or world-state consequence beyond the "
                f"do-target itself. The auditor counts any "
                f"manufactured downstream effect as a miracle step."
            )
        else:
            _instr = (
                f"=== CASCADE-BOUNDED CONSEQUENCES (HARD) === \u2014 the "
                f"{rung_label} surgery propagated exactly {n_total} "
                f"downstream effect(s) listed under DOWNSTREAM TRAIT / "
                f"RELATIONSHIP / PROPOSITION / BELIEF / CONCERN CASCADES "
                f"in the {world_label} sandbox payload. That list is "
                f"AUTHORITATIVE: render every cascade as a concrete "
                f"on-page beat AND do NOT invent additional downstream "
                f"effects beyond it. Any consequence the engine did not "
                f"propagate would be a miracle step \u2014 the auditor "
                f"flags both omitted cascades and invented consequences "
                f"by counting the gap against this list."
            )
        blocks.append(ConstraintBlock(
            constraint_type="mathematical",
            priority="hard",
            instruction=_instr,
            evidence={
                "cascade_total": n_total,
                "trait_count": len(mutations or []),
                "social_count": len(social_mutations or []),
                "proposition_count": len(proposition_mutations or []),
                "belief_count": len(belief_mutations or []),
                "concern_count": len(concern_mutations or []),
                "blocked_count": len(blocked or []),
            },
        ))

    # 2. Blocked-propagation pink-elephant block. Each blocked entry
    # carries a "would-have-been" new_value; we deliberately do NOT
    # surface it. The renderer is told the (node, trait) is forbidden
    # to depict as changed, and that the *resistance* must be staged
    # instead.
    blocked_clean = [b for b in (blocked or []) if isinstance(b, dict)]
    if blocked_clean:
        lines = []
        for b in blocked_clean[:25]:
            node = b.get("node_id", "?")
            trait = b.get("trait", "?")
            reason = b.get("reason", "unknown")
            lines.append(
                f"  \u2022 {node}.{trait} \u2014 resistance: {reason}"
            )
        if len(blocked_clean) > 25:
            lines.append(f"  \u2022 \u2026 + {len(blocked_clean) - 25} more.")
        # Renderer-budget guard. Staging an on-page resistance beat
        # for every blocked propagation is impossible in a 500-2000
        # word scene once the list exceeds ~5 entries — the renderer
        # is forced to either sketch them all (auditor fires
        # ``blocked_propagation_leak`` on the half-rendered cues) or
        # skip most (auditor fires ``abduction_failure``). When the
        # list is short, demand explicit resistance beats; when it is
        # long, the directive flips to "treat these traits as stable
        # and do NOT stage them" so the renderer stops oscillating
        # between the two failure modes. Stable behaviour is still
        # implicitly rendered (the character's normal baseline), it
        # is just not foregrounded as a resistance beat.
        _BLOCKED_STAGE_CAP = 2
        if len(blocked_clean) <= _BLOCKED_STAGE_CAP:
            _blocked_directive = (
                f"=== BLOCKED PROPAGATIONS (HARD) === \u2014 the engine "
                f"applied the {rung_label} cascade but the targets "
                f"below RESISTED. They DID NOT reach the propagated "
                f"state in the {world_label} world. Do NOT render any "
                f"line that names, depicts, implies, or interiorises "
                f"the (node, trait) below as having reached the new "
                f"value \u2014 the would-have-been target is "
                f"intentionally NOT shown to you so you cannot pattern-"
                f"match on it. Render the RESISTANCE as a single "
                f"concrete beat per entry: the force, inertia, "
                f"affordance constraint, or cyclic absorption that "
                f"stopped the change from taking hold. The auditor "
                f"cross-checks that no blocked target appears in its "
                f"propagated state on-page.\n"
                + "\n".join(lines)
            )
        else:
            _blocked_directive = (
                f"=== BLOCKED PROPAGATIONS (HARD) === \u2014 the engine "
                f"applied the {rung_label} cascade but the "
                f"{len(blocked_clean)} (node, trait) targets below "
                f"RESISTED and DID NOT reach the propagated state in "
                f"the {world_label} world. The list is too long to "
                f"stage one resistance beat per entry within the "
                f"scene's word budget. Instead, treat every trait "
                f"below as STABLE at its prior value: do NOT render "
                f"any line that names, depicts, implies, or "
                f"interiorises any (node, trait) below as having "
                f"shifted, AND do NOT manufacture a separate "
                f"resistance beat for each \u2014 the character's "
                f"ordinary baseline behaviour is sufficient evidence "
                f"of stability. The auditor checks for the propagated "
                f"state appearing on-page, not for explicit resistance "
                f"prose.\n"
                + "\n".join(lines)
            )
        blocks.append(ConstraintBlock(
            constraint_type="mathematical",
            priority="hard",
            instruction=_blocked_directive,
            evidence={
                "blocked_node_traits": [
                    f"{b.get('node_id', '?')}.{b.get('trait', '?')}"
                    for b in blocked_clean
                ],
                "blocked_directive_mode": (
                    "stage_resistance"
                    if len(blocked_clean) <= _BLOCKED_STAGE_CAP
                    else "treat_as_stable"
                ),
            },
        ))

    # 3. Rule-3 pruned interventions. The local clamp holds at the
    # target node, but downstream consequences are vacuous. In
    # ``advisory`` mode the rule3 list is informational; in ``prune``
    # mode the engine excised them and the renderer must treat them
    # as if they were never applied.
    pruned = list(rule3_pruned_interventions or [])
    if pruned:
        prune_mode_hard = rule3_pruning_mode == "prune"
        lines = [f"  \u2022 {p}" for p in pruned[:25]]
        if len(pruned) > 25:
            lines.append(f"  \u2022 \u2026 + {len(pruned) - 25} more.")
        if prune_mode_hard:
            blocks.append(ConstraintBlock(
                constraint_type="mathematical",
                priority="hard",
                instruction=(
                    f"=== VACUOUS {rung_label} SURGERIES (HARD, Rule-3 "
                    f"pruned) === \u2014 the do-surgeries below were "
                    f"provably disconnected from the query's outcome "
                    f"set on the AMWN. The local clamp at each target "
                    f"holds in the {world_label} world, but NO "
                    f"downstream consequence may be rendered for any "
                    f"of them. Do NOT extend new effects to entities, "
                    f"beliefs, or events not directly named by the "
                    f"surgery target. The auditor flags any prose that "
                    f"narrates a downstream effect traceable to a "
                    f"pruned key.\n"
                    + "\n".join(lines)
                ),
                evidence={"rule3_pruned_interventions": pruned},
            ))
        else:
            blocks.append(ConstraintBlock(
                constraint_type="mathematical",
                priority="soft",
                instruction=(
                    f"VACUOUS {rung_label} SURGERIES (advisory, Rule-3 "
                    f"flagged) \u2014 the do-surgeries below have no "
                    f"directed path to the query outcomes. Renderer is "
                    f"warned but not forced; the auditor will surface "
                    f"any invented downstream consequence for these as "
                    f"a soft finding.\n"
                    + "\n".join(lines)
                ),
                evidence={"rule3_pruned_interventions": pruned},
            ))

    return blocks


def _build_exclusion_constraints(
    pruned_utterance_event_ids: Optional[List[str]],
    disabled_channel_ids: Optional[List[str]],
    world_state: WorldStateV1,
    *,
    world_label: str,
) -> List[ConstraintBlock]:
    """Build HARD ConstraintBlocks for utterances/channels the engine
    severed via do-surgery (Rung-2 intervention or Rung-3 counterfactual).

    ``world_label`` is interpolated into the instruction text so the
    renderer sees branch-appropriate wording (e.g. ``"counterfactual"``
    vs ``"intervened"``). The auditor's deterministic withheld-utterance
    check is keyed on ``syuzhet_index`` and does not cover engine-side
    deletion, so without these blocks the renderer reliably re-introduces
    canonical lines that are still present in ``preceding_prose`` /
    ``factual_contrast_summary``.
    """
    blocks: List[ConstraintBlock] = []
    pruned_utts = [u for u in (pruned_utterance_event_ids or []) if u]
    disabled_chs = [c for c in (disabled_channel_ids or []) if c]
    if pruned_utts:
        events_by_id = {e.id: e for e in getattr(world_state, "events", []) or []}
        lines: List[str] = []
        for uid in pruned_utts[:20]:
            evt = events_by_id.get(uid)
            if evt is None:
                lines.append(f"  - {uid}")
                continue
            speaker = getattr(evt, "speaker_id", None) or "unknown"
            addressees = list(getattr(evt, "addressee_ids", []) or [])
            # Anti-pink-elephant: do NOT show ``content`` verbatim. The
            # canonical text is exactly what we are forbidding the
            # renderer to echo, so quoting it in the "do not echo"
            # instruction reliably makes it the most salient phrase
            # in the prompt and the renderer either reproduces it
            # verbatim or paraphrases its evidentiary logic. Show only
            # a *structural fingerprint* — the speech-act shape that
            # is forbidden, not the wording. The id slug
            # (e.g.\u00a0EVT_UTT_GEORGE_ORDERS_KEN_KILL_COADY) carries
            # enough semantic content for the renderer to know which
            # speech act is forbidden without showing it the line.
            target_ids = list(getattr(evt, "target_ids", []) or [])
            truth_value = getattr(evt, "truth_value", None) or ""
            via_channel = getattr(evt, "via_channel_id", None) or ""
            fp_parts: list[str] = []
            if target_ids:
                fp_parts.append(f"about={target_ids}")
            if truth_value:
                fp_parts.append(f"truth={truth_value}")
            if via_channel:
                fp_parts.append(f"via={via_channel}")
            fingerprint = (" | " + ", ".join(fp_parts)) if fp_parts else ""
            lines.append(
                f"  - {uid}: speaker={speaker} \u2192 "
                f"addressees={addressees}{fingerprint}"
            )
        if len(pruned_utts) > 20:
            lines.append(f"  - ...and {len(pruned_utts) - 20} more.")
        blocks.append(ConstraintBlock(
            constraint_type="narrative",
            priority="hard",
            instruction=(
                # Begin with the exact === ERASED UTTERANCES (HARD) ===
                # marker the renderer/auditor prompt files reference,
                # so an LLM that pattern-matches on the heading sees
                # it verbatim, not just the prefix words inside a
                # generic constraints dump.
                f"=== ERASED UTTERANCES (HARD) === \u2014 the speech acts "
                f"identified below were SPOKEN in canon but the do-"
                f"surgery severed their provenance and they DO NOT "
                f"exist in this {world_label} world. The canonical "
                "wording is intentionally NOT shown to you \u2014 only the "
                "speaker, addressees, and topic structure. Do NOT have "
                "any character perform this speech act in any form: "
                "do not echo, paraphrase, remember, or recreate the "
                "evidentiary logic, intent, or causal claim of the "
                "erased line. If the same speaker would naturally "
                "still talk to the same addressee in this scene, "
                "invent a NEW line about a DIFFERENT subject (or a "
                "different evidentiary justification) consistent with "
                "the changed conditions. The auditor will flag both "
                "verbatim quotation and structural paraphrase \u2014 the "
                "act-shape is what is forbidden, not just the wording.\n"
                + "\n".join(lines)
            ),
            evidence={"pruned_utterance_event_ids": pruned_utts},
        ))
    if disabled_chs:
        chs_by_id = getattr(world_state, "channels", {}) or {}
        ch_lines: List[str] = []
        for cid in disabled_chs[:20]:
            ch = chs_by_id.get(cid)
            if ch is None:
                ch_lines.append(f"  - {cid}")
                continue
            medium = getattr(ch, "medium", "?")
            participants = list(getattr(ch, "participant_ids", []) or [])
            ch_lines.append(
                f"  - {cid} ({medium}, participants={participants})"
            )
        if len(disabled_chs) > 20:
            ch_lines.append(f"  - ...and {len(disabled_chs) - 20} more.")
        blocks.append(ConstraintBlock(
            constraint_type="narrative",
            priority="hard",
            instruction=(
                # Same marker-fidelity reasoning as the erased-
                # utterances block above.
                f"=== DISABLED CHANNELS (HARD) === \u2014 these communication "
                f"links existed in canon but the do-surgery removed "
                f"their carrier; they DO NOT exist in this {world_label} "
                "world. Do NOT route any new dialogue or signal "
                "through them, do not refer to them by name, and do "
                "not show characters expecting messages on them.\n"
                + "\n".join(ch_lines)
            ),
            evidence={"disabled_channel_ids": disabled_chs},
        ))
    return blocks


def build_intervention_brief(
    query: InterventionQuery,
    physics_state: Dict[str, Any],
    world_state: WorldStateV1,
    mutations: Optional[List[Dict[str, Any]]] = None,
    blocked: Optional[List[Dict[str, Any]]] = None,
    rule3_pruned_interventions: Optional[List[str]] = None,
    rule2_redundant_evidence: Optional[List[str]] = None,
    rule3_pruning_mode: Literal["advisory", "prune"] = "advisory",
    pruned_utterance_event_ids: Optional[List[str]] = None,
    disabled_channel_ids: Optional[List[str]] = None,
    skipped_interventions: Optional[List[Dict[str, Any]]] = None,
    affected_propositions: Optional[List[str]] = None,
    affected_beliefs: Optional[List[str]] = None,
    affected_concerns: Optional[List[str]] = None,
    social_mutations: Optional[List[Dict[str, Any]]] = None,
    proposition_mutations: Optional[List[Dict[str, Any]]] = None,
    belief_mutations: Optional[List[Dict[str, Any]]] = None,
    concern_mutations: Optional[List[Dict[str, Any]]] = None,
    causal_chain: Optional[List[str]] = None,
    *,
    preceding_prose: Optional[str] = None,
    branch_world_id: Literal["factual", "shadow"] = "factual",
    branch_label: Optional[str] = None,
    factual_contrast_summary: Optional[str] = None,
    syuzhet_anchor: Optional[int] = None,
    intervention_inert: bool = False,
    intervention_inert_reason: Optional[str] = None,
) -> CreativeBrief:
    """Build a CreativeBrief for intervention (do-calculus) queries."""
    pruned_set = set(rule3_pruned_interventions or [])
    is_prune_mode = rule3_pruning_mode == "prune"

    # Build InterventionMechanism entries from the interventions dict
    mechanisms: List[InterventionMechanism] = []
    for target_path, new_value in query.interventions.items():
        parts = target_path.split(".", 1)
        node_id = parts[0]
        prop = parts[1] if len(parts) > 1 else "state"

        # Try to find the old state
        old_state = "unknown"
        if node_id in world_state.entities:
            if prop == "status":
                old_state = world_state.entities[node_id].status
            elif prop.startswith("traits."):
                trait_name = prop.split(".", 1)[1]
                tv = world_state.entities[node_id].traits.get(trait_name)
                old_state = f"{tv.value:.2f}" if tv else "unknown"
            elif prop.startswith("relationships."):
                # ``relationships.<other>.<axis>`` — walk social_topology
                # for the per-axis baseline. Without this branch the
                # InterventionMechanism block sent to the rendering LLM
                # and the auditor reports ``old_state="unknown"`` and
                # ``mechanism="physical"`` for any social do-surgery.
                rel_parts = prop.split(".")
                if len(rel_parts) >= 3:
                    other_id = rel_parts[1]
                    axis = rel_parts[2]
                    for rel in world_state.social_topology:
                        if (
                            rel.source_entity_id == node_id
                            and rel.target_entity_id == other_id
                        ):
                            m = rel.metrics.get(axis)
                            if m is not None:
                                old_state = f"{m.value:+.2f}"
                            break
        elif node_id in world_state.objects:
            old_state = world_state.objects[node_id].properties.get(prop, "unknown")

        # Determine mechanism from the property type
        mechanism = "physical"
        if prop.startswith("traits."):
            mechanism = "psychological force overcoming inertia"
        elif prop.startswith("relationships."):
            mechanism = "social pressure overcoming relationship inertia"
        elif prop == "status":
            mechanism = "physical force or environmental change"
        elif prop == "location_id":
            mechanism = "physical movement"

        # Find inertia if applicable
        inertia = 0.5
        if node_id in world_state.entities and prop.startswith("traits."):
            trait_name = prop.split(".", 1)[1]
            tv = world_state.entities[node_id].traits.get(trait_name)
            if tv:
                inertia = tv.inertia
        elif node_id in world_state.entities and prop.startswith("relationships."):
            rel_parts = prop.split(".")
            if len(rel_parts) >= 3:
                other_id = rel_parts[1]
                axis = rel_parts[2]
                for rel in world_state.social_topology:
                    if (
                        rel.source_entity_id == node_id
                        and rel.target_entity_id == other_id
                    ):
                        m = rel.metrics.get(axis)
                        if m is not None:
                            inertia = m.inertia
                        break

        mechanisms.append(InterventionMechanism(
            node_id=node_id,
            old_state=old_state,
            new_state=str(new_value),
            mechanism_hint=mechanism,
            inertia=inertia,
            vacuous=(target_path in pruned_set and is_prune_mode),
            advisory=(target_path in pruned_set and not is_prune_mode),
        ))

    constraints: List[ConstraintBlock] = list(_user_intent_constraints(query.original_query))
    # Scene-internal grounding constraint (mirrors the counterfactual
    # rung). The intervention rung performs do-surgery but the scene is
    # still the actual lived world post-intervention; the renderer must
    # not slip into "what would have happened" subjunctive framing.
    constraints.append(ConstraintBlock(
        constraint_type="narrative",
        priority="hard",
        instruction=(
            "Render this scene as the actual lived world \u2014 concrete "
            "physical action, sensory detail, and character behaviour, "
            "in plain past-tense narration. Do NOT use author-voice "
            "conditional or subjunctive framing (\"if he had\u2026\", "
            "\"would have\u2026\"). The events of this scene are what "
            "actually happened in this world."
        ),
        evidence={},
    ))
    # Blocked propagations become constraints. The
    # ``_build_cascade_exclusion_constraints`` helper above already
    # emits a single consolidated BLOCKED PROPAGATIONS block (and
    # flips its directive between "stage one resistance beat per
    # entry" and "treat as stable, no per-entry resistance beats"
    # once the list exceeds the ~5-beat scene budget). Mirror that
    # cap here so we do not append 25 separate hard constraints
    # demanding 25 distinct resistance beats — that is what forced
    # the renderer to oscillate between blocked_propagation_leak
    # (sketched too many) and abduction_failure (skipped most).
    if blocked:
        _BLOCKED_PER_ENTRY_CAP = 5
        if len(blocked) <= _BLOCKED_PER_ENTRY_CAP:
            for b in blocked:
                constraints.append(ConstraintBlock(
                    constraint_type="spatial",
                    priority="hard",
                    instruction=(
                        f"BLOCKED: The propagation to {b.get('node_id', '?')}.{b.get('trait', '?')} "
                        f"was blocked by {b.get('reason', 'unknown')}. "
                        f"The state change did NOT propagate \u2014 render one concrete resistance beat."
                    ),
                    evidence=b,
                ))
        else:
            # Long blocked list: emit a single aggregate constraint
            # that forbids the propagated state but does NOT demand a
            # per-entry resistance beat. The consolidated
            # pink-elephant block above carries the full enumeration
            # in its ``evidence``.
            constraints.append(ConstraintBlock(
                constraint_type="spatial",
                priority="hard",
                instruction=(
                    f"BLOCKED ({len(blocked)} entries): the (node, trait) "
                    f"targets enumerated in the BLOCKED PROPAGATIONS "
                    f"pink-elephant block did NOT change. Treat each as "
                    f"stable at its prior value; the character's "
                    f"ordinary baseline behaviour is sufficient \u2014 "
                    f"do NOT manufacture a separate resistance beat "
                    f"for each entry."
                ),
                evidence={"blocked_count": len(blocked)},
            ))

    # ctf-calculus pre-flight prunings (Correa & Bareinboim 2025).
    # The engine proved these surgeries vacuous against the user's targets
    # before simulation. The prose MUST NOT invent downstream effects for
    # them — the do-operator was applied locally but is provably
    # disconnected from the rest of the AMWN.
    if rule3_pruned_interventions:
        if rule3_pruning_mode == "prune":
            constraints.append(ConstraintBlock(
                constraint_type="mathematical",
                priority="hard",
                instruction=(
                    "VACUOUS INTERVENTIONS (Rule-3 pruned): "
                    f"{', '.join(rule3_pruned_interventions)}. These surgeries "
                    "have no directed path to any target on the AMWN. Render "
                    "the local change at the intervened node, but do NOT "
                    "describe causal ripples reaching other characters or "
                    "downstream events — the engine proved there are none."
                ),
                evidence={"rule3_pruned": list(rule3_pruned_interventions)},
            ))
        else:
            # Advisory mode: AMWN flagged these as vacuous against the
            # extracted graph, but the engine still ran the surgery
            # because a missed confounder could mask a real causal path.
            # Surface as a SOFT note so the LLM down-weights (but does
            # not suppress) downstream effects.
            constraints.append(ConstraintBlock(
                constraint_type="mathematical",
                priority="soft",
                instruction=(
                    "AMWN ADVISORY (Rule-3): the static causal diagram "
                    "shows no directed path from "
                    f"{', '.join(rule3_pruned_interventions)} to the query "
                    "targets. The do-surgery WAS still applied (advisory "
                    "mode) because the extracted topology may be missing "
                    "latent confounders. Treat downstream consequences "
                    "of these interventions as plausible-but-uncertain; "
                    "prefer subtle echoes over loud causal chains."
                ),
                evidence={"rule3_advisory": list(rule3_pruned_interventions)},
            ))

    # ctf-calculus Rule-2 advisory \u2014 mirrors the counterfactual brief
    # (round-9 audit fix). Intervention briefs accepted but never
    # surfaced ``rule2_redundant_evidence``; the renderer therefore had
    # no signal that some evidence anchors were d-separated from the
    # surgery and should be treated as background colour.
    if rule2_redundant_evidence:
        constraints.append(ConstraintBlock(
            constraint_type="mathematical",
            priority="soft",
            instruction=(
                "REDUNDANT EVIDENCE (Rule-2): "
                f"{', '.join(rule2_redundant_evidence)} are d-separated "
                "from the typed interventions on the AMWN. They did not "
                "constrain the surgery's reach \u2014 treat them as "
                "background colour, not evidential anchors for the change."
            ),
            evidence={"rule2_redundant": list(rule2_redundant_evidence)},
        ))

    constraints.append(ConstraintBlock(
        constraint_type="mathematical",
        priority="hard",
        instruction=(
            "You MUST describe the exact physical mechanism that caused each "
            "state change. Do NOT just say 'the door opened' — render the "
            "physical struggle or action that forced the Impact to overcome "
            "the Inertia. The reader must feel the force required."
        ),
        evidence={},
    ))

    # Channels & beliefs subsystem: the Rung-2 do-surgery can sever
    # downstream utterances and channels (e.g. intervening on a
    # speaker's status removes the lines they would have spoken). The
    # renderer needs to know which canonical lines / links no longer
    # exist in this intervened world; without this block they bleed
    # back in via ``preceding_prose`` / ``factual_contrast_summary``.
    constraints.extend(_build_exclusion_constraints(
        pruned_utterance_event_ids,
        disabled_channel_ids,
        world_state,
        world_label="intervened",
    ))
    # Pink-elephant cascade EXCLUSIONS: bound the rendered cascade
    # to exactly the engine's propagation log, forbid depicting any
    # blocked target in its propagated state, and (in prune mode)
    # forbid downstream consequences for Rule-3 vacuous surgeries.
    # The existing rule3 constraint above is broad-strokes advisory;
    # this block names the forbidden categories pink-elephant-safely
    # (no would-be value, no canonical wording) so both renderer and
    # auditor enforce the same bound.
    constraints.extend(_build_cascade_exclusion_constraints(
        blocked=blocked,
        rule3_pruned_interventions=None,  # already covered above
        mutations=mutations,
        social_mutations=social_mutations,
        proposition_mutations=proposition_mutations,
        belief_mutations=belief_mutations,
        concern_mutations=concern_mutations,
        rule3_pruning_mode=rule3_pruning_mode,
        world_label="intervened",
        rung_label="Rung-2 intervention",
    ))
    constraints.extend(_build_inert_intervention_constraints(
        intervention_inert=intervention_inert,
        intervention_inert_reason=intervention_inert_reason,
        rung_label="Rung-2 intervention",
        world_label="intervened",
    ))
    # Negative-physics record: prevented events + false propositions.
    constraints.extend(_build_skipped_intervention_constraints(
        skipped_interventions,
    ))
    constraints.extend(build_prevented_event_constraints(
        world_state, syuzhet_anchor, world_label="intervened",
    ))
    # Severed-chain CONTEXT + positive substitution. Without these
    # the renderer routinely confabulates a substitute failure mode
    # ("missing canine evidence", "absent witness") for any character
    # whose plan depended on a pruned event. Both blocks are gated on
    # the do-surgery actually pruning something (no-op on Rung-1).
    constraints.extend(build_prune_cascade_context_constraints(
        world_state, pruned_utterance_event_ids,
        world_label="intervened",
    ))
    constraints.extend(build_dependent_state_substitution_constraints(
        world_state, pruned_utterance_event_ids,
        affected_beliefs=affected_beliefs,
        affected_concerns=affected_concerns,
        world_label="intervened",
    ))
    constraints.extend(build_false_proposition_constraints(
        world_state, syuzhet_anchor, world_label="intervened",
    ))
    constraints.extend(build_unrealised_concern_constraints(
        world_state, syuzhet_anchor, world_label="intervened",
    ))
    constraints.extend(build_false_belief_grounding_constraints(
        world_state, syuzhet_anchor, world_label="intervened",
    ))
    constraints.extend(build_object_coherence_constraints(
        world_state,
        _syuzhet_to_fabula_anchor(world_state, syuzhet_anchor),
        world_label="intervened",
    ))

    # Resolve POV roster from the do-targets so multi-entity
    # interventions don't silently collapse to the first one. Defaults
    # to ``rotating`` per-beat coverage; the assembler can later swap
    # to ``ensemble`` for omniscient-constrained scenes.
    _intervention_targets = _entities_from_intervention_keys(
        query.interventions, world_state,
    )
    _intervention_pov = _resolve_pov_policy(_intervention_targets)
    # Mirror the Rung-3 fallback chain in ``build_counterfactual_brief``:
    # if no typed ``do_targets`` were supplied, coerce them from the
    # legacy dotted-key ``interventions`` dict. Without this Rung-2
    # queries parsed from the legacy LLM shape (``{"EVT_X.event_type":
    # "prevented"}``) reach the renderer with ``do_target=None`` and
    # the "RUNG-2 SURGERY KIND" / event-prevention hints silently drop.
    _ib_do_targets = list(getattr(query, "do_targets", None) or [])
    if not _ib_do_targets and getattr(query, "interventions", None):
        from shadow_loom.query_models import _coerce_legacy_dict
        _ib_do_targets = list(_coerce_legacy_dict(query.interventions))
    _ib_primary_do_target = _ib_do_targets[0] if _ib_do_targets else None

    return CreativeBrief(
        target_effect="intervention",
        target_entities=_intervention_targets,
        original_query=query.original_query,
        constraints=constraints,
        narrative_style=getattr(world_state, "narrative_style", None),
        preceding_prose=preceding_prose,
        branch_world_id=branch_world_id,
        branch_label=branch_label,
        factual_contrast_summary=factual_contrast_summary,
        # Surface the engine-authored multi-room split-screen / channel
        # severance text the Rung-2 physics emits on ``physics_state``.
        # Without this lift the renderer/auditor never see the
        # ``=== PHYSICS OVERRIDE (HARD) ===`` block on intervention
        # queries and the engine's per-location override silently
        # vanishes between physics and prose.
        physics_override=(
            physics_state.get("physics_override")
            if isinstance(physics_state, dict) else None
        ),
        # Withheld-utterance / hidden-channel set (see
        # ``build_observation_brief`` for rationale).
        hidden_channels=compute_hidden_channels_for(
            world_state, syuzhet_anchor,
        ),
        rendering=RenderingDirective(
            rendering_mode="intervention",
            pov_lock=_intervention_pov[0],
            additional_pov_locks=_intervention_pov[1],
            pov_policy=_intervention_pov[2],
            pacing="normal",
            sensory_focus="normal",
            stylistic_instructions=[
                "Ground the prose in concrete physical reality \u2014 what "
                "the POV character sees, hears, touches, and does, "
                "moment by moment.",
                "Describe the exact physical mechanism for each state change (do-operator).",
                "Render the struggle between Impact and Inertia as physical prose.",
                "Show the cause producing the effect through a specific mechanism "
                "(kinetic, chemical, social, psychological).",
                "If a propagation was blocked, the (node, trait) did NOT move. "
                "When the BLOCKED PROPAGATIONS block asks for resistance beats, "
                "stage one concrete beat of the force or inertia that held the "
                "prior value \u2014 never a near-change or a subtle cue of a "
                "shift. When the block asks you to treat the list as stable, "
                "do NOT manufacture per-entry resistance prose; the character's "
                "ordinary baseline behaviour is sufficient.",
                "Render the scene as the lived present of this world. Do "
                "not stand outside it as a narrator commenting on its "
                "structure.",
            ],
        ),
        intervention_mechanisms=mechanisms,
        # Rung-2 sandbox payload: typed do_target(s) + flipped
        # propositions / beliefs / concerns. Mirrors the Rung-3
        # ``counterfactual_branch`` channel so the renderer and
        # auditor can verify the prose grounds every node the
        # surgery touched. Empty when the legacy event-only path
        # supplied the intervention.
        intervention_branch=InterventionBranch(
            do_target=_ib_primary_do_target,
            do_target_gloss=_resolve_do_target_gloss(world_state, _ib_primary_do_target),
            do_target_context=_format_do_target_causal_context(world_state, _ib_primary_do_target),
            do_targets=[
                t.model_dump() if hasattr(t, "model_dump") else dict(t)
                for t in _ib_do_targets
            ],
            affected_propositions=list(affected_propositions or []),
            affected_proposition_descriptions=_resolve_affected_descriptions(
                world_state, list(affected_propositions or []), "prop",
            ),
            affected_beliefs=list(affected_beliefs or []),
            affected_belief_descriptions=_resolve_affected_descriptions(
                world_state, list(affected_beliefs or []), "belief",
            ),
            affected_concerns=list(affected_concerns or []),
            affected_concern_descriptions=_resolve_affected_descriptions(
                world_state, list(affected_concerns or []), "concern",
            ),
            causal_chain=list(causal_chain or []),
            causal_chain_descriptions=_resolve_affected_descriptions(
                world_state, list(causal_chain or []), "event",
            ),
            **_build_downstream_cascade_payload(
                mutations=mutations,
                social_mutations=social_mutations,
                proposition_mutations=proposition_mutations,
                belief_mutations=belief_mutations,
                concern_mutations=concern_mutations,
                blocked=blocked,
            ),
        ) if (
            getattr(query, "do_targets", None)
            or affected_propositions
            or affected_beliefs
            or affected_concerns
            or mutations
            or social_mutations
            or proposition_mutations
            or belief_mutations
            or concern_mutations
            or blocked
        ) else None,
        scene_context=(
            {**physics_state, "syuzhet_anchor": syuzhet_anchor}
            if syuzhet_anchor is not None
            and isinstance(physics_state, dict)
            and "syuzhet_anchor" not in physics_state
            else physics_state
        ),
    )


def build_counterfactual_brief(
    query: CounterfactualQuery,
    physics_state: Dict[str, Any],
    world_state: WorldStateV1,
    hidden_deltas: Optional[Dict[str, Dict[str, float]]] = None,
    rule3_pruned_interventions: Optional[List[str]] = None,
    rule2_redundant_evidence: Optional[List[str]] = None,
    rule3_pruning_mode: Literal["advisory", "prune"] = "advisory",
    pruned_utterance_event_ids: Optional[List[str]] = None,
    disabled_channel_ids: Optional[List[str]] = None,
    skipped_interventions: Optional[List[Dict[str, Any]]] = None,
    affected_propositions: Optional[List[str]] = None,
    affected_beliefs: Optional[List[str]] = None,
    affected_concerns: Optional[List[str]] = None,
    historical_do_targets: Optional[List[Dict[str, Any]]] = None,
    mutations: Optional[List[Dict[str, Any]]] = None,
    social_mutations: Optional[List[Dict[str, Any]]] = None,
    proposition_mutations: Optional[List[Dict[str, Any]]] = None,
    belief_mutations: Optional[List[Dict[str, Any]]] = None,
    concern_mutations: Optional[List[Dict[str, Any]]] = None,
    blocked: Optional[List[Dict[str, Any]]] = None,
    causal_chain: Optional[List[str]] = None,
    *,
    preceding_prose: Optional[str] = None,
    branch_world_id: Literal["factual", "shadow"] = "factual",
    branch_label: Optional[str] = None,
    factual_contrast_summary: Optional[str] = None,
    syuzhet_anchor: Optional[int] = None,
    intervention_inert: bool = False,
    intervention_inert_reason: Optional[str] = None,
) -> CreativeBrief:
    """Build a CreativeBrief for counterfactual (Rung 3) queries."""
    # Build AbductionTruth entries from hidden_deltas.
    #
    # Filter out near-zero deltas (|delta| < 0.10). When the Rung-3
    # propagator hits a cyclic SCC or noisy-OR absorption it returns
    # impact=0.00..0.18 across most traits, which the auditor then
    # flags as "abduction failures" because the prose can't render
    # observable cues for shifts that the simulator itself called
    # negligible. The renderer is asked to invent observable behaviour
    # for an effectively-flat trait distribution — and if it does, the
    # POV-lock auditor flags those exact cues as "diagnostic gloss
    # exceeding perceptual bounds". Dropping near-zero entries here
    # cuts that double-jeopardy at the source. (May 2026 Star Wars
    # counterfactual non-convergence audit.)
    _ABDUCTION_MIN_DELTA = 0.10
    # Build a (entity, trait) lookup of every blocked propagation so we
    # can drop overlapping abduction entries. The BLOCKED PROPAGATIONS
    # constraint block (see ``_build_cascade_exclusion_constraints``)
    # tells the renderer the (node, trait) did NOT change and forbids
    # depicting / interiorising it as changed; the AbductionTruth
    # ``weave_hint`` for the same trait would simultaneously demand a
    # subtle behavioural cue revealing the hidden shift. The two
    # instructions are mutually unsatisfiable: any micro-reaction the
    # renderer writes for AbductionTruth is interiorisation of the
    # trait as changed, which the BLOCKED block forbids and the
    # auditor's ``blocked_propagation_leak`` then flags. Resistance
    # wins (the engine's verdict is that the delta was never realised).
    _blocked_keys: set = set()
    for _b in (blocked or []):
        if not isinstance(_b, dict):
            continue
        _bnode = _b.get("node_id")
        _btrait = _b.get("trait")
        if _bnode and _btrait:
            _blocked_keys.add((_bnode, _btrait))
    abduction: List[AbductionTruth] = []
    if hidden_deltas:
        skipped_flat = 0
        skipped_blocked = 0
        for entity_id, deltas in hidden_deltas.items():
            for trait, delta_val in deltas.items():
                if (entity_id, trait) in _blocked_keys:
                    skipped_blocked += 1
                    continue
                if abs(float(delta_val)) < _ABDUCTION_MIN_DELTA:
                    skipped_flat += 1
                    continue
                direction = "increased" if delta_val > 0 else "decreased"
                abduction.append(AbductionTruth(
                    entity_id=entity_id,
                    hidden_variable=(
                        f"{trait} {direction} by {abs(delta_val):.2f} "
                        f"(inferred from present-day evidence)"
                    ),
                    weave_hint=(
                        f"Show this through subtle behavioral cues — {entity_id}'s "
                        f"body language, word choice, or micro-reactions should "
                        f"reveal the hidden {trait} shift without exposition."
                    ),
                ))
        if skipped_flat:
            logger.info(
                "[CounterfactualBrief] Skipped %d sub-threshold abduction "
                "shifts (|delta| < %.2f) — propagator likely hit a cyclic "
                "or noisy-OR-absorbed cluster; rendering would be invented "
                "and immediately flagged as POV/abduction conflicts.",
                skipped_flat, _ABDUCTION_MIN_DELTA,
            )
        if skipped_blocked:
            logger.info(
                "[CounterfactualBrief] Skipped %d abduction shifts whose "
                "(entity, trait) overlap with BLOCKED PROPAGATIONS — "
                "resistance wins so the AbductionTruth weave_hint would "
                "contradict the blocked-propagation directive and trigger "
                "blocked_propagation_leak in the auditor.",
                skipped_blocked,
            )

    # Build a counterfactual branch from the intervention keys.
    # Phrasing is scene-internal: the renderer must treat the simulated
    # state as the *actual world* of the scene (Rule 10 / generation
    # Category 3 COUNTERFACTUAL). No "alternate timeline / divergence /
    # branch / what-if" vocabulary leaks into the brief — the renderer
    # echoes brief vocabulary verbatim and the meta-narration auditor
    # then rejects it.
    hist_keys = list(query.historical_interventions.keys())
    # Phase-9 sandbox coverage: populate the structured surgery payload
    # (do_target + affected_propositions / beliefs / concerns) so the
    # renderer and auditor see WHICH nodes the Rung-3 surgery touches
    # across the plot — not just the natural-language summary above.
    # Without this both surfaces fell through to empty lists and the
    # auditor's "RUNG-3 SURGERY KIND" / "AFFECTED PROPOSITIONS" lines
    # rendered nothing, leaving the shadow path uncovered.
    # Resolve the typed Rung-3 surgery target from (in priority order):
    #   1. the ``historical_do_targets`` parameter forwarded by the
    #      generation entry-point from ``physics_result``;
    #   2. ``query.historical_do_targets`` populated by the typed query
    #      coercion path;
    #   3. a fallback coercion from the legacy dotted-key
    #      ``query.historical_interventions`` dict.
    # Without (1) and (3) the legacy path produced an empty
    # ``do_target`` here, the renderer's ``RUNG-3 SURGERY KIND`` hint
    # never fired, and the precursor-attempt-survival guidance for
    # ``event``-kind surgeries was silently dropped — letting the
    # renderer rewrite a prevented murder attempt as a benign visit
    # instead of the intended "attempt survives, outcome differs"
    # counterfactual.
    def _as_do_target_list(items: Any) -> List[Any]:
        from shadow_loom.query_models import DoTarget  # local to avoid cycle
        out: List[Any] = []
        for item in items or []:
            if isinstance(item, dict):
                # ``DoTarget`` is a discriminated union — validate via
                # pydantic so the right variant is reconstructed.
                try:
                    from pydantic import TypeAdapter
                    out.append(TypeAdapter(DoTarget).validate_python(item))
                except Exception:
                    continue
            else:
                out.append(item)
        return out

    _hist_do_targets = _as_do_target_list(historical_do_targets)
    if not _hist_do_targets:
        _hist_do_targets = list(
            getattr(query, "historical_do_targets", None) or []
        )
    if not _hist_do_targets and getattr(query, "historical_interventions", None):
        from shadow_loom.query_models import _coerce_legacy_dict
        _hist_do_targets = list(
            _coerce_legacy_dict(query.historical_interventions)
        )
    _cf_do_target = _hist_do_targets[0] if _hist_do_targets else None
    # Prefer the typed ``DoEvent.event_id`` for the divergence anchor
    # when available — falls back to splitting the legacy dotted key.
    # Without this fallback chain a counterfactual that supplies only
    # typed ``historical_do_targets`` (no legacy ``historical_interventions``
    # dict) reaches the renderer with ``divergence_event_id=None`` and
    # the "POINT OF DIVERGENCE: …" line silently drops from the prompt.
    _divergence_event_id: Optional[str] = None
    if _cf_do_target is not None:
        _divergence_event_id = getattr(_cf_do_target, "event_id", None)
    if not _divergence_event_id and hist_keys:
        _divergence_event_id = hist_keys[0].split(".")[0]
    cf_branch = CounterfactualBranch(
        actual_outcome="Events as they occurred in the established record.",
        simulated_outcome=(
            f"Events as they unfold under the changed conditions: "
            f"{query.historical_interventions}"
        ),
        divergence_event_id=_divergence_event_id,
        do_target=_cf_do_target,
        do_target_gloss=_resolve_do_target_gloss(world_state, _cf_do_target),
        do_target_context=_format_do_target_causal_context(world_state, _cf_do_target),
        affected_propositions=list(affected_propositions or []),
        affected_proposition_descriptions=_resolve_affected_descriptions(
            world_state, list(affected_propositions or []), "prop",
        ),
        affected_beliefs=list(affected_beliefs or []),
        affected_belief_descriptions=_resolve_affected_descriptions(
            world_state, list(affected_beliefs or []), "belief",
        ),
        affected_concerns=list(affected_concerns or []),
        affected_concern_descriptions=_resolve_affected_descriptions(
            world_state, list(affected_concerns or []), "concern",
        ),
        causal_chain=list(causal_chain or []),
        causal_chain_descriptions=_resolve_affected_descriptions(
            world_state, list(causal_chain or []), "event",
        ),
        **_build_downstream_cascade_payload(
            mutations=mutations,
            social_mutations=social_mutations,
            proposition_mutations=proposition_mutations,
            belief_mutations=belief_mutations,
            concern_mutations=concern_mutations,
            blocked=blocked,
        ),
    )

    constraints = [
        *_user_intent_constraints(query.original_query),
        ConstraintBlock(
            constraint_type="narrative",
            priority="hard",
            instruction=(
                "Render this scene as the actual lived world — concrete "
                "physical action, sensory detail, and character behaviour, "
                "in plain past-tense narration. Do NOT use author-voice "
                "conditional or subjunctive framing (\"if he had…\", "
                "\"would have…\"). The events of this scene are what "
                "actually happened in this world."
            ),
            evidence={},
        ),
    ]

    if abduction:
        constraints.append(ConstraintBlock(
            constraint_type="mathematical",
            priority="hard",
            instruction=(
                "Abduction background truths have been inferred by the physics "
                "engine. You MUST weave these into the subtext smoothly — through "
                "casual actions, body language, or environmental details. "
                "Do NOT use clunky exposition. The NarrativeAuditor will check "
                "that these hidden variables are structurally present."
            ),
            evidence={},
        ))

    # ctf-calculus pre-flight prunings (Correa & Bareinboim 2025).
    if rule3_pruned_interventions:
        if rule3_pruning_mode == "prune":
            constraints.append(ConstraintBlock(
                constraint_type="mathematical",
                priority="hard",
                instruction=(
                    "VACUOUS HISTORICAL INTERVENTIONS (Rule-3 pruned): "
                    f"{', '.join(rule3_pruned_interventions)}. These do-surgeries "
                    "have no directed path to the present-day evidence on the "
                    "AMWN. The change at the intervened node holds locally, "
                    "but the rest of the world is unchanged — do NOT extend "
                    "new downstream consequences to the broader story."
                ),
                evidence={"rule3_pruned": list(rule3_pruned_interventions)},
            ))
        else:
            constraints.append(ConstraintBlock(
                constraint_type="mathematical",
                priority="soft",
                instruction=(
                    "AMWN ADVISORY (Rule-3): the static causal diagram "
                    "shows no directed path from "
                    f"{', '.join(rule3_pruned_interventions)} to present-"
                    "day evidence. The do-surgery WAS still applied "
                    "(advisory mode); the extracted topology may be "
                    "missing latent confounders. Render downstream "
                    "consequences cautiously — favour atmospheric shifts "
                    "over explicit causal chains."
                ),
                evidence={"rule3_advisory": list(rule3_pruned_interventions)},
            ))
    if rule2_redundant_evidence:
        constraints.append(ConstraintBlock(
            constraint_type="mathematical",
            priority="soft",
            instruction=(
                "REDUNDANT EVIDENCE (Rule-2): "
                f"{', '.join(rule2_redundant_evidence)} are d-separated "
                "from the historical interventions on the AMWN. Their "
                "present-day state did not constrain the abduction — treat "
                "them as background colour, not evidential anchors."
            ),
            evidence={"rule2_redundant": list(rule2_redundant_evidence)},
        ))

    # Surface the present-day evidence the abduction was conditioned on.
    # The auditor / generator otherwise have no idea which observed facts
    # anchored the latent-trait inference, and the prose can drift away
    # from the user's stated grounding.
    evidence_ids = list(getattr(query, "evidence_node_ids", []) or [])
    if evidence_ids:
        constraints.append(ConstraintBlock(
            constraint_type="mathematical",
            priority="hard",
            instruction=(
                "PRESENT-DAY EVIDENCE (abduction was conditioned on these "
                f"node states): {', '.join(evidence_ids)}. The scene must "
                "remain consistent with these observed facts where they are "
                "not directly contradicted by the historical intervention "
                "— they are the anchor that justified the inferred "
                "hidden-variable shifts."
            ),
            evidence={"evidence_node_ids": evidence_ids},
        ))

    # ERASED-BY-DIVERGENCE EXCLUSIONS.
    # The Rung-3 surgery removes utterances and channels whose
    # provenance was severed by the historical intervention. Telling
    # the renderer *what no longer exists* in this counterfactual
    # world is as important as telling it what does — without this
    # block the renderer reliably re-introduces canonical lines
    # ("she said the things she had always said") because they are
    # still present in ``preceding_prose`` / ``factual_contrast``
    # even though the engine deleted them. The auditor's
    # withheld-utterance leak check (which is keyed off
    # ``syuzhet_index``) does not cover deletion, so leaks here
    # appear as silent canon-bleed instead of typed violations.
    constraints.extend(_build_exclusion_constraints(
        pruned_utterance_event_ids,
        disabled_channel_ids,
        world_state,
        world_label="counterfactual",
    ))
    # Pink-elephant cascade EXCLUSIONS for Rung-3: same uniform
    # bound as Rung-2 — render only the engine's propagation log,
    # never depict blocked targets in their propagated state.
    constraints.extend(_build_cascade_exclusion_constraints(
        blocked=blocked,
        rule3_pruned_interventions=None,  # covered elsewhere on this brief
        mutations=mutations,
        social_mutations=social_mutations,
        proposition_mutations=proposition_mutations,
        belief_mutations=belief_mutations,
        concern_mutations=concern_mutations,
        rule3_pruning_mode=rule3_pruning_mode,
        world_label="counterfactual",
        rung_label="Rung-3 counterfactual",
    ))
    constraints.extend(_build_inert_intervention_constraints(
        intervention_inert=intervention_inert,
        intervention_inert_reason=intervention_inert_reason,
        rung_label="Rung-3 counterfactual",
        world_label="counterfactual",
    ))
    # Negative-physics record: prevented events + false propositions.
    constraints.extend(_build_skipped_intervention_constraints(
        skipped_interventions,
    ))
    constraints.extend(build_prevented_event_constraints(
        world_state, syuzhet_anchor, world_label="counterfactual",
    ))
    # Severed-chain CONTEXT + positive substitution (same pair as
    # the Rung-2 brief above). Closes the gap that lets the renderer
    # invent a NEW failure-mode for plans whose original cause was
    # pruned: it now sees both the severed parent\u2192child links
    # AND the current post-prune entity status to render against.
    constraints.extend(build_prune_cascade_context_constraints(
        world_state, pruned_utterance_event_ids,
        world_label="counterfactual",
    ))
    constraints.extend(build_dependent_state_substitution_constraints(
        world_state, pruned_utterance_event_ids,
        affected_beliefs=affected_beliefs,
        affected_concerns=affected_concerns,
        world_label="counterfactual",
    ))
    constraints.extend(build_false_proposition_constraints(
        world_state, syuzhet_anchor, world_label="counterfactual",
    ))
    constraints.extend(build_unrealised_concern_constraints(
        world_state, syuzhet_anchor, world_label="counterfactual",
    ))
    constraints.extend(build_false_belief_grounding_constraints(
        world_state, syuzhet_anchor, world_label="counterfactual",
    ))
    constraints.extend(build_object_coherence_constraints(
        world_state,
        _syuzhet_to_fabula_anchor(world_state, syuzhet_anchor),
        world_label="counterfactual",
    ))

    # Resolve target entities from the historical intervention keys
    # (entity props OR event participants) and union with any explicit
    # downstream target nodes the user named.
    target_entities = _entities_from_intervention_keys(
        query.historical_interventions, world_state
    )
    extra_targets = _entities_from_intervention_keys(
        getattr(query, "target_node_ids", []) or [], world_state
    )
    for eid in extra_targets:
        if eid not in target_entities:
            target_entities.append(eid)

    _ctf_pov = _resolve_pov_policy(target_entities)

    return CreativeBrief(
        target_effect="counterfactual",
        target_entities=target_entities,
        original_query=query.original_query,
        constraints=constraints,
        narrative_style=getattr(world_state, "narrative_style", None),
        preceding_prose=preceding_prose,
        branch_world_id=branch_world_id,
        branch_label=branch_label,
        factual_contrast_summary=factual_contrast_summary,
        # See build_intervention_brief for rationale: the Rung-3
        # physics emits a multi-room override on ``physics_state``
        # that must reach the renderer/auditor brief or it is silently
        # dropped.
        physics_override=(
            physics_state.get("physics_override")
            if isinstance(physics_state, dict) else None
        ),
        # Withheld-utterance / hidden-channel set (see
        # ``build_observation_brief`` for rationale).
        hidden_channels=compute_hidden_channels_for(
            world_state, syuzhet_anchor,
        ),
        rendering=RenderingDirective(
            rendering_mode="counterfactual",
            pov_lock=_ctf_pov[0],
            additional_pov_locks=_ctf_pov[1],
            pov_policy=_ctf_pov[2],
            pacing="normal",
            sensory_focus="normal",
            stylistic_instructions=[
                "Ground the prose in concrete physical reality — what the "
                "POV character sees, hears, touches, and does, moment by "
                "moment.",
                "If the changed conditions yield a better outcome than the "
                "established record, let the prose feel cautiously hopeful "
                "— but fragile.",
                "If the changed conditions yield a worse outcome, let the "
                "prose feel eerily wrong.",
                "Weave abduction background truths into character behaviour "
                "naturally — body language, micro-reactions, environmental "
                "detail — never as exposition.",
                "Render the scene as the lived present of this world. Do "
                "not stand outside it as a narrator commenting on its "
                "structure.",
            ],
        ),
        counterfactual_branch=cf_branch,
        abduction_truths=abduction,
        scene_context=(
            {**physics_state, "syuzhet_anchor": syuzhet_anchor}
            if syuzhet_anchor is not None
            and isinstance(physics_state, dict)
            and "syuzhet_anchor" not in physics_state
            else physics_state
        ),
    )


