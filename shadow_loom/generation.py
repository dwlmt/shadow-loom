    _loss_desc = getattr(rp, "loss_description", None)
    if _div_desc:
        lines.append(f"  Divergence event: \"{_div_desc}\"")
    if _loss_desc:
        lines.append(f"  Loss event: \"{_loss_desc}\"")
    return "\n".join(lines)


