def _load_prompt(filename: str) -> str:
    path = _PROMPTS_DIR / filename
    if not path.exists():
        raise FileNotFoundError(f"Prompt file not found: {path}")
    return path.read_text(encoding="utf-8")


def _resolve_model(model_str: str):
    if model_str.startswith("ollama:"):
        base_url = os.environ.get("OLLAMA_BASE_URL", _OLLAMA_BASE_URL)
        model_name = model_str.split(":", 1)[1]
        from pydantic_ai.models.ollama import OllamaModel
        from pydantic_ai.providers.ollama import OllamaProvider
        return OllamaModel(model_name, provider=OllamaProvider(base_url=base_url))
    return model_str


def _format_constraints(constraints: List[ConstraintBlock]) -> str:
    """Format ConstraintBlocks into a numbered constraint list."""
    if not constraints:
        return "(No constraints.)"
    lines: List[str] = []
    for i, c in enumerate(constraints, 1):
        priority_tag = "HARD" if c.priority == "hard" else "SOFT"
        lines.append(f"  {i}. [{priority_tag} | {c.constraint_type.upper()}] {c.instruction}")
    return "\n".join(lines)


def _format_rendering_directive(r: RenderingDirective) -> str:
    """Format a RenderingDirective into prose instructions."""
    parts = [
        f"RENDERING MODE: {r.rendering_mode}",
        f"PACING: {r.pacing}",
        f"SENSORY FOCUS: {r.sensory_focus}",
    ]
    if r.pov_lock:
        parts.append(f"POV LOCKED TO: {r.pov_lock}")
    if r.tone_arc:
        parts.append(f"TONAL ARC: {r.tone_arc}")
    if r.stylistic_instructions:
        parts.append("STYLISTIC ACTIONS:")
        for j, si in enumerate(r.stylistic_instructions, 1):
            parts.append(f"  {j}. {si}")
    return "\n".join(parts)


def _format_threat_proximity(tp: ThreatProximity) -> str:
    lines = ["THREAT PROXIMITY:"]
    if tp.threat_event_id:
        lines.append(f"  Threat event: {tp.threat_event_id}")
    lines.append(f"  Description: {tp.threat_description}")
    lines.append(f"  P(threat): {tp.threat_probability:.2f}")
    lines.append(f"  P(hope): {tp.hope_probability:.2f}")
    lines.append(f"  Damage potential: {tp.damage_potential:.1f}/10")
    if tp.spatial_distance is not None:
        lines.append(f"  Spatial distance: {tp.spatial_distance} hops")
    return "\n".join(lines)


def _format_counterfactual(cf: CounterfactualBranch) -> str:
    lines = [
        "COUNTERFACTUAL BRANCH:",
        f"  ACTUAL OUTCOME: {cf.actual_outcome}",
        f"  SIMULATED (better) OUTCOME: {cf.simulated_outcome}",
    ]
    if cf.divergence_event_id:
        lines.append(f"  POINT OF DIVERGENCE: {cf.divergence_event_id}")
    if cf.divergence_description:
        lines.append(f"    → {cf.divergence_description}")
    return "\n".join(lines)


def _format_causal_attribution(ca: CausalAttribution) -> str:
    lines = [
        "CAUSAL ATTRIBUTION:",
        f"  PERPETRATOR: {ca.perpetrator_id}" + (f" ({ca.perpetrator_name})" if ca.perpetrator_name else ""),
        f"  LOSS EVENT: {ca.loss_event_id} — {ca.loss_description}",
    ]
    if ca.causal_chain:
        lines.append(f"  CAUSAL CHAIN: {' → '.join(ca.causal_chain)}")
    return "\n".join(lines)


def _format_entanglement(pairs: List[EntanglementPair]) -> str:
    if not pairs:
        return ""
    lines = ["ENTANGLEMENT PAIRS:"]
    for p in pairs:
        co = " (co-located)" if p.shared_location else " (separated)"
        lines.append(f"  {p.entity_a} ↔ {p.entity_b}: coupling={p.coupling_strength:.2f}{co}")
    return "\n".join(lines)


def _format_interventions(mechs: List[InterventionMechanism]) -> str:
    if not mechs:
        return ""
    lines = ["INTERVENTION PHYSICS (do-operator state changes you MUST render):"]
    for m in mechs:
        lines.append(
            f"  {m.node_id}: {m.old_state} → {m.new_state} "
            f"via {m.mechanism_hint} (inertia={m.inertia:.2f})"
        )
    return "\n".join(lines)


def _format_abduction(truths: List[AbductionTruth]) -> str:
    if not truths:
        return ""
    lines = ["ABDUCTION BACKGROUND TRUTHS (weave into subtext — do NOT use clunky exposition):"]
    for t in truths:
        hint = f" Hint: {t.weave_hint}" if t.weave_hint else ""
        lines.append(f"  {t.entity_id}: {t.hidden_variable}.{hint}")
    return "\n".join(lines)


def _format_scene_context(ctx: Dict[str, Any]) -> str:
    """Build a concise scene context from the ego-graph payload."""
    lines: List[str] = []

    # Focus entities
    for ent in ctx.get("focus_entities", []):
        eid = ent.get("id", "?")
        name = ent.get("name", eid)
        loc = ent.get("location_id", "unknown")
        status = ent.get("status", "unknown")
        traits = ent.get("traits", {})
        trait_parts = []
        for tn, td in traits.items():
            if isinstance(td, dict):
                val = td.get("value", 0.5)
                if abs(val - 0.5) >= 0.15:
                    trait_parts.append(f"{tn}={val:.2f}")
        trait_str = ", ".join(trait_parts) if trait_parts else "baseline"
        lines.append(f"  {name} ({eid}) — {status}, at {loc} [{trait_str}]")

    # Present entities
    for ent in ctx.get("present_entities", []):
        eid = ent.get("id", "?")
        name = ent.get("name", eid)
        loc = ent.get("location_id", "unknown")
        lines.append(f"  {name} ({eid}) — present at {loc}")

    # Locations (ego-graph uses "current_locations")
    for loc in ctx.get("current_locations", ctx.get("relevant_locations", [])):
        lid = loc.get("id", "?")
        lname = loc.get("name", lid)
        lines.append(f"  Location: {lname} ({lid})")

    # Recent events (from memory)
    for evt in ctx.get("recent_memory", []):
        eid = evt.get("id", "?")
        desc = evt.get("description", "")
        lines.append(f"  Recent: {eid} — {desc}")

    if not lines:
        return "(No scene context available.)"
    return "\n".join(lines)


def assemble_rendering_prompt(
    brief: CreativeBrief,
    query_type: str = "directive",
    physics_state: Optional[Dict[str, Any]] = None,
) -> str:
    """Assemble the full semantic prompt injection from a CreativeBrief.

    This is the "Step 9 → Step 10" bridge: all mathematical constraints,
    rendering directives, and scene context are flattened into a single
    text block that the LLM can consume as a user message.
    """
    sections: List[str] = []

    # === Header ===
    sections.append(f"=== GENERATION TASK: {brief.target_effect.upper()} ===")
    sections.append(f"Target entities: {', '.join(brief.target_entities)}")
    sections.append("")

    # === Scene Context ===
    sections.append("=== SCENE CONTEXT ===")
    sections.append(_format_scene_context(brief.scene_context))
    sections.append("")

    # === Mathematical Constraints (the guardrails) ===
    sections.append("=== CONSTRAINTS (Step 9 — Semantic Prompt Injection) ===")
    sections.append(_format_constraints(brief.constraints))
    sections.append("")

    # === Rendering Directive (the stylistic control layer) ===
    if brief.rendering:
        sections.append("=== RENDERING DIRECTIVE (Step 10 — How to write) ===")
        sections.append(_format_rendering_directive(brief.rendering))
        sections.append("")

    # === Effect-specific payloads ===
    if brief.threat_proximity:
        sections.append(_format_threat_proximity(brief.threat_proximity))
        sections.append("")

    if brief.counterfactual_branch:
        sections.append(_format_counterfactual(brief.counterfactual_branch))
        sections.append("")

    if brief.causal_attribution:
        sections.append(_format_causal_attribution(brief.causal_attribution))
        sections.append("")

    if brief.entanglement_pairs:
        sections.append(_format_entanglement(brief.entanglement_pairs))
        sections.append("")

    if brief.intervention_mechanisms:
        sections.append(_format_interventions(brief.intervention_mechanisms))
        sections.append("")

    if brief.abduction_truths:
        sections.append(_format_abduction(brief.abduction_truths))
        sections.append("")

    # === Physics Override ===
    if brief.physics_override:
        sections.append(f"=== PHYSICS OVERRIDE ===\n{brief.physics_override}")
        sections.append("")

    # === Epistemic Gaps (reference data) ===
    if brief.epistemic_gaps:
        sections.append("=== EPISTEMIC STATE (character beliefs vs reality) ===")
        for g in brief.epistemic_gaps:
            sections.append(
                f"  {g.entity_id} re {g.belief_target_id}: "
                f"believes='{g.believed_state}' actual='{g.actual_state}' "
                f"({g.gap_type}, mag={g.gap_magnitude:.2f})"
            )
        sections.append("")

    # === Trait Trajectories (reference data) ===
    if brief.trait_trajectories:
        extreme = [t for t in brief.trait_trajectories if abs(t.current_value - 0.5) >= 0.15]
        if extreme:
            sections.append("=== KEY TRAIT STATES ===")
            for t in extreme:
                sections.append(
                    f"  {t.entity_id}.{t.trait_name} = {t.current_value:.2f} "
                    f"(inertia={t.inertia:.2f}, headroom↑={t.headroom_up:.2f}, headroom↓={t.headroom_down:.2f})"
                )
            sections.append("")

    # === Relationship Tensions (reference data) ===
    if brief.relationship_tensions:
        tense = [r for r in brief.relationship_tensions if r.asymmetry_score > 0.1]
        if tense:
            sections.append("=== RELATIONSHIP TENSIONS ===")
            for r in tense:
                sections.append(
                    f"  {r.source_id}→{r.target_id}: affinity={r.affinity:.2f}, "
                    f"fear={r.fear:.2f}, power={r.power_dynamic:.2f} "
                    f"(asymmetry={r.asymmetry_score:.2f})"
                )
            sections.append("")

    sections.append(
        "=== TASK ===\n"
        "Write the prose passage now. Honour ALL hard constraints. "
        "The prose must structurally validate against the mathematical "
        "state described above. The NarrativeAuditor will check that "
        "the rendered text is consistent with the physics."
    )

    return "\n".join(sections)


