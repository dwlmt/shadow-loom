def render_scene(
    brief: CreativeBrief,
    config: GenerationConfig | None = None,
    query_type: str = "directive",
    physics_state: Optional[Dict[str, Any]] = None,
) -> GeneratedScene:
    """Render a prose scene from a CreativeBrief.

    This is the main entry point for Step 10.

    Parameters
    ----------
    brief : CreativeBrief
        The assembled brief from directive_assembly (or a brief builder).
    config : GenerationConfig or None
        Model and retry configuration.
    query_type : str
        The originating query type for prompt framing.
    physics_state : dict or None
        Raw physics state for additional context.

    Returns
    -------
    GeneratedScene
        The rendered prose with audit metadata.
    """
    config = config or GenerationConfig()

    rendering_prompt = assemble_rendering_prompt(brief, query_type, physics_state)
    logger.info(
        "[Generation] Rendering scene: effect=%s entities=%s mode=%s",
        brief.target_effect,
        brief.target_entities,
        brief.rendering.rendering_mode if brief.rendering else "default",
    )
    logger.debug("[Generation] Prompt length: %d chars", len(rendering_prompt))

    agent = _build_generation_agent(config)
    deps = _GenerationDeps(rendering_prompt=rendering_prompt)

    model_settings: Dict[str, Any] = {}
    if config.temperature != 0.7:
        model_settings["temperature"] = config.temperature
    model_settings["max_tokens"] = config.max_tokens

    try:
        result = agent.run_sync(
            f"Render the scene now. Target effect: {brief.target_effect}.",
            deps=deps,
            model_settings=model_settings if model_settings else None,
        )
        scene = result.output
        log_agent_output(logger, "Generation", scene)
    except Exception as exc:
        logger.error("[Generation] LLM call failed: %s. Returning fallback scene.", exc)
        return GeneratedScene(
            prose=f"[Generation failed: {exc}]",
            pov_entity=None,
            rendering_mode="fallback",
            constraints_honoured=[],
            constraints_violated=["generation_failure"],
            generation_error=repr(exc),
        )

    logger.info(
        "[Generation] Scene rendered: %d chars, mode=%s, %d constraints honoured, %d violated",
        len(scene.prose),
        scene.rendering_mode,
        len(scene.constraints_honoured),
        len(scene.constraints_violated),
    )
    return scene


def render_from_query(
    request: UserRequest,
    physics_result: Dict[str, Any],
    world_state: WorldStateV1,
    config: GenerationConfig | None = None,
    *,
    preceding_prose: Optional[str] = None,
    branch_world_id: Literal["factual", "shadow"] = "factual",
    branch_label: Optional[str] = None,
    factual_contrast_summary: Optional[str] = None,
    syuzhet_anchor: Optional[int] = None,
) -> GeneratedScene:
    """High-level convenience: build a brief from any query type and render.

    This routes from the raw ``calculate_narrative_physics()`` output
    directly to prose generation.

    Parameters
    ----------
    request : UserRequest
        The original user query.
    physics_result : dict
        The output of ``calculate_narrative_physics()``.
    world_state : WorldStateV1
        The global world state for context.
    config : GenerationConfig or None
        Generation configuration.
    preceding_prose : str or None
        Story-so-far excerpt threaded onto the brief by ``run_pipeline``
        so a chain of queries renders prose that is narratively
        continuous with everything that came before. Forwarded into
        every brief builder; ignored for ``directive`` queries that
        already carry a pre-built brief from the assembler (those are
        stamped at the pipeline call-site instead).

    Returns
    -------
    GeneratedScene
    """
    config = config or GenerationConfig()
    physics_state = physics_result.get("physics_state", {})

    if request.query_type == "observation":
        brief = build_observation_brief(
            request, physics_state, world_state,
            preceding_prose=preceding_prose,
            branch_world_id=branch_world_id,
            branch_label=branch_label,
            factual_contrast_summary=factual_contrast_summary,
            syuzhet_anchor=syuzhet_anchor,
        )
        return render_scene(brief, config, "observation", physics_state)

    elif request.query_type == "intervention":
        brief = build_intervention_brief(
            request,
            physics_state,
            world_state,
            mutations=physics_result.get("mutations"),
            blocked=physics_result.get("blocked"),
            rule3_pruned_interventions=physics_result.get("rule3_pruned_interventions"),
            rule2_redundant_evidence=physics_result.get("rule2_redundant_evidence"),
            rule3_pruning_mode=physics_result.get("rule3_pruning_mode", "advisory"),
            pruned_utterance_event_ids=physics_result.get("pruned_utterance_event_ids"),
            disabled_channel_ids=physics_result.get("disabled_channel_ids"),
            preceding_prose=preceding_prose,
            branch_world_id=branch_world_id,
            branch_label=branch_label,
            factual_contrast_summary=factual_contrast_summary,
            syuzhet_anchor=syuzhet_anchor,
        )
        return render_scene(brief, config, "intervention", physics_state)

    elif request.query_type == "counterfactual":
        brief = build_counterfactual_brief(
            request,
            physics_state,
            world_state,
            hidden_deltas=physics_result.get("hidden_deltas"),
            rule3_pruned_interventions=physics_result.get("rule3_pruned_interventions"),
            rule2_redundant_evidence=physics_result.get("rule2_redundant_evidence"),
            rule3_pruning_mode=physics_result.get("rule3_pruning_mode", "advisory"),
            pruned_utterance_event_ids=physics_result.get("pruned_utterance_event_ids"),
            disabled_channel_ids=physics_result.get("disabled_channel_ids"),
            preceding_prose=preceding_prose,
            branch_world_id=branch_world_id,
            branch_label=branch_label,
            factual_contrast_summary=factual_contrast_summary,
            syuzhet_anchor=syuzhet_anchor,
        )
        return render_scene(brief, config, "counterfactual", physics_state)

    elif request.query_type == "directive":
        # Directive queries should already have a creative_brief in physics_result
        brief_data = physics_result.get("creative_brief")
        if brief_data:
            brief = CreativeBrief(**brief_data) if isinstance(brief_data, dict) else brief_data
        else:
            # Fallback: build a minimal brief. The fallback historically
            # omitted ``rendering`` entirely, which silently dropped the
            # stylistic_instructions / pov_lock contract on directive
            # paths whose physics_state did not carry a ``creative_brief``
            # (e.g. minimal pipelines, test harnesses). Mirror the
            # universal grounding directive the other rungs ship so
            # ``narrative_style`` is not the only style anchor on this
            # path.
            target_eff = physics_result.get("target_effect", "observation")
            target_ents = list(getattr(request, "target_entity_ids", []) or [])
            fallback_constraints: List[ConstraintBlock] = list(
                _user_intent_constraints(getattr(request, "original_query", None))
            )
            fallback_constraints.append(ConstraintBlock(
                constraint_type="narrative",
                priority="hard",
                instruction=(
                    "Render this scene as the actual lived world \u2014 "
                    "concrete physical action, sensory detail, and "
                    "character behaviour, in plain past-tense narration. "
                    "Do NOT use author-voice conditional or subjunctive "
                    "framing (\"if he had\u2026\", \"would have\u2026\"). "
                    "The events of this scene are what actually "
                    "happened in this world."
                ),
                evidence={},
            ))
            brief = CreativeBrief(
                target_effect=target_eff,
                target_entities=target_ents,
                original_query=getattr(request, "original_query", None),
                constraints=fallback_constraints,
                scene_context=physics_state,
                narrative_style=getattr(world_state, "narrative_style", None),
                rendering=RenderingDirective(
                    rendering_mode=str(target_eff),
                    pov_lock=target_ents[0] if target_ents else None,
                    pacing="normal",
                    sensory_focus="normal",
                    stylistic_instructions=[
                        "Ground the prose in concrete physical reality "
                        "\u2014 what the POV character sees, hears, "
                        "touches, and does, moment by moment.",
                        "Render the scene as the lived present of this "
                        "world. Do not stand outside it as a narrator "
                        "commenting on its structure.",
                    ],
                ),
            )
        if preceding_prose and not brief.preceding_prose:
            brief.preceding_prose = preceding_prose
        # Stamp branch context onto the brief — directive paths that
        # bypass the pipeline-level stamping (e.g. skip_audit) would
        # otherwise lose the shadow-branch framing.
        brief.branch_world_id = branch_world_id
        if branch_label is not None:
            brief.branch_label = branch_label
        if factual_contrast_summary is not None and not brief.factual_contrast_summary:
            brief.factual_contrast_summary = factual_contrast_summary
        return render_scene(brief, config, "directive", physics_state)

    elif request.query_type == "interrogate":
        raise ValueError(
            "Interrogation queries return graph analysis, not prose. "
            "Do not call render_from_query for interrogation."
        )

    else:
        raise ValueError(f"Unknown query type: {request.query_type}")
