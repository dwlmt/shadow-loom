# Public API
# =====================================================================

def render_scene(
    brief: CreativeBrief,
    config: GenerationConfig | None = None,
    query_type: str = "directive",
    physics_state: Optional[Dict[str, Any]] = None,
) -> GeneratedScene:
    """Render a prose scene from a CreativeBrief.

    This is the main entry point for Step 10.

    Parameters
    ----------
    brief : CreativeBrief
        The assembled brief from directive_assembly (or a brief builder).
    config : GenerationConfig or None
        Model and retry configuration.
    query_type : str
        The originating query type for prompt framing.
    physics_state : dict or None
        Raw physics state for additional context.

    Returns
    -------
    GeneratedScene
        The rendered prose with audit metadata.
    """
    config = config or GenerationConfig()

    rendering_prompt = assemble_rendering_prompt(brief, query_type, physics_state)
    logger.info(
        "[Generation] Rendering scene: effect=%s entities=%s mode=%s",
        brief.target_effect,
        brief.target_entities,
        brief.rendering.rendering_mode if brief.rendering else "default",
    )
    logger.debug("[Generation] Prompt length: %d chars", len(rendering_prompt))

    agent = _build_generation_agent(config)
    deps = _GenerationDeps(rendering_prompt=rendering_prompt)

    model_settings: Dict[str, Any] = {}
    if config.temperature != 0.7:
        model_settings["temperature"] = config.temperature
    if config.max_tokens != 4096:
        model_settings["max_tokens"] = config.max_tokens

    try:
        result = agent.run_sync(
            f"Render the scene now. Target effect: {brief.target_effect}.",
            deps=deps,
            model_settings=model_settings if model_settings else None,
        )
        scene = result.output
    except Exception as exc:
        logger.error("[Generation] LLM call failed: %s. Returning fallback scene.", exc)
        return GeneratedScene(
            prose=f"[Generation failed: {exc}]",
            pov_entity=None,
            rendering_mode="fallback",
            constraints_honoured=[],
            constraints_violated=["generation_failure"],
        )

    logger.info(
        "[Generation] Scene rendered: %d chars, mode=%s, %d constraints honoured, %d violated",
        len(scene.prose),
        scene.rendering_mode,
        len(scene.constraints_honoured),
        len(scene.constraints_violated),
    )
    return scene


def render_from_query(
    request: UserRequest,
    physics_result: Dict[str, Any],
    world_state: WorldStateV1,
    config: GenerationConfig | None = None,
) -> GeneratedScene:
    """High-level convenience: build a brief from any query type and render.

    This routes from the raw ``calculate_narrative_physics()`` output
    directly to prose generation.

    Parameters
    ----------
    request : UserRequest
        The original user query.
    physics_result : dict
        The output of ``calculate_narrative_physics()``.
    world_state : WorldStateV1
        The global world state for context.
    config : GenerationConfig or None
        Generation configuration.

    Returns
    -------
    GeneratedScene
    """
    config = config or GenerationConfig()
    physics_state = physics_result.get("physics_state", {})

    if request.query_type == "observation":
        brief = build_observation_brief(request, physics_state, world_state)
        return render_scene(brief, config, "observation", physics_state)

    elif request.query_type == "intervention":
        brief = build_intervention_brief(
            request,
            physics_state,
            world_state,
            mutations=physics_result.get("mutations"),
            blocked=physics_result.get("blocked"),
        )
        return render_scene(brief, config, "intervention", physics_state)

    elif request.query_type == "counterfactual":
        brief = build_counterfactual_brief(
            request,
            physics_state,
            world_state,
            hidden_deltas=physics_result.get("hidden_deltas"),
        )
        return render_scene(brief, config, "counterfactual", physics_state)

    elif request.query_type == "directive":
        # Directive queries should already have a creative_brief in physics_result
        brief_data = physics_result.get("creative_brief")
        if brief_data:
            brief = CreativeBrief(**brief_data) if isinstance(brief_data, dict) else brief_data
        else:
            # Fallback: build a minimal brief
            brief = CreativeBrief(
                target_effect=physics_result.get("target_effect", "observation"),
                target_entities=getattr(request, "target_entity_ids", []),
                scene_context=physics_state,
            )
        return render_scene(brief, config, "directive", physics_state)

    elif request.query_type == "interrogate":
        raise ValueError(
            "Interrogation queries return graph analysis, not prose. "
            "Do not call render_from_query for interrogation."
        )

    else:
        raise ValueError(f"Unknown query type: {request.query_type}")
