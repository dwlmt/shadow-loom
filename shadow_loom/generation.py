"""
Step 10 — LLM Rendering (The Generation Step).

The Large Language Model operates strictly as a **renderer**.  It takes the
Semantic Prompt Injection (the mathematical guardrails and constraints
generated by the DirectiveAssembler in Step 9) and translates them into
natural-language prose.

The generation step is conditioned on query type:
  - Observation  → neutral scene rendering from ego-graph state
  - Intervention → describe the physical mechanism of a do-operator state change
  - Counterfactual → weave the "what-if" into character monologue / narration
  - Directive     → maximise a specific narrative/emotional effect per CreativeBrief

For Directive queries, the 10 target effects each trigger distinct rendering
strategies (pacing, sensory focus, tonal arc, POV lock, etc.) that are
encoded in the ``RenderingDirective`` attached to the ``CreativeBrief``.
"""

