def _entities_from_intervention_keys(
    intervention_keys: Iterable[str],
    world_state: WorldStateV1,
) -> List[str]:
    """Resolve an ``interventions`` dict's keys to a deduplicated list of
    entity IDs.

    Intervention keys may target entities directly (``ENT_KEN.fear``) or
    events (``EVT_KEN_KILLS_DOGS.outcome``).  For the event case we
    expand to the event's actors and targets so the rendered brief
    knows which entities the alternate timeline is about — without
    these the prompt logs ``entities=[]`` and downstream prompt
    sections that key off ``brief.target_entities`` (POV selection,
    auditor focus, etc.) get nothing to work with.
    """
    events_by_id = {e.id: e for e in getattr(world_state, "events", []) or []}
    seen: List[str] = []
    seen_set: set[str] = set()

    def _add(eid: str) -> None:
        if eid and eid.startswith("ENT_") and eid not in seen_set:
            seen_set.add(eid)
            seen.append(eid)

    for key in intervention_keys:
        node_id = key.split(".", 1)[0]
        if node_id.startswith("ENT_"):
            _add(node_id)
        elif node_id.startswith("EVT_") and node_id in events_by_id:
            evt = events_by_id[node_id]
            for aid in getattr(evt, "actor_ids", []) or []:
                _add(aid)
            for tid in getattr(evt, "target_ids", []) or []:
                _add(tid)
    return seen


def _user_intent_constraints(original_query: Optional[str]) -> List[ConstraintBlock]:
    """Lift the user's verbatim NL request into a HARD constraint.

    Mirrors the equivalent block at the top of
    ``DirectiveAssembler.assemble`` so non-directive briefs (observation,
    intervention, counterfactual, evaluation fallback) also bind the
    rendering and audit prompts to the user's actual ask. Returns an
    empty list when no original query is available so callers can
    splat it unconditionally.
    """
    text = (original_query or "").strip()
    if not text:
        return []
    return [ConstraintBlock(
        constraint_type="narrative",
        priority="hard",
        instruction=(
            f"[USER INTENT \u2014 verbatim]: {text}\n"
            "The rendered scene MUST address the user's request above. "
            "Engine-derived constraints below are guard-rails, not "
            "substitutes for the user's intent."
        ),
        evidence={"original_query": text},
    )]


def build_observation_brief(
    query: ObservationQuery,
    physics_state: Dict[str, Any],
    world_state: WorldStateV1,
    *,
    preceding_prose: Optional[str] = None,
    branch_world_id: Literal["factual", "shadow"] = "factual",
    branch_label: Optional[str] = None,
    factual_contrast_summary: Optional[str] = None,
    syuzhet_anchor: Optional[int] = None,
) -> CreativeBrief:
    """Build a lightweight CreativeBrief for observation queries."""
    pov = query.focus_entity_ids[0] if query.focus_entity_ids else None
    constraints: List[ConstraintBlock] = _user_intent_constraints(query.original_query)
    # Scene-internal grounding constraint (mirrors the counterfactual
    # rung). Without this the rung-1 prose is free to drift into
    # author-voice meta framing because the rendering directive's
    # ``stylistic_instructions`` are advisory; the constraint block
    # makes scenic grounding HARD across every prose-generating rung
    # so the auditor's stylistic checks have something concrete to bind
    # to and the ``narrative_style`` block is not the only style anchor.
    constraints.append(ConstraintBlock(
        constraint_type="narrative",
        priority="hard",
        instruction=(
            "Render this scene as the actual lived world \u2014 concrete "
            "physical action, sensory detail, and character behaviour, "
            "in plain past-tense narration. Do NOT use author-voice "
            "conditional or subjunctive framing (\"if he had\u2026\", "
            "\"would have\u2026\"). The events of this scene are what "
            "actually happened in this world."
        ),
        evidence={},
    ))
    # Negative-physics record: events the world tags as not occurring
    # and propositions committed FALSE at or before the anchor must
    # NOT be staged as having happened. Applies to every rung.
    constraints.extend(build_prevented_event_constraints(
        world_state, syuzhet_anchor, world_label="observed",
    ))
    constraints.extend(build_false_proposition_constraints(
        world_state, syuzhet_anchor, world_label="observed",
    ))
    scene_context = dict(physics_state) if isinstance(physics_state, dict) else {}
    if syuzhet_anchor is not None and isinstance(scene_context, dict):
        scene_context.setdefault("syuzhet_anchor", syuzhet_anchor)
    return CreativeBrief(
        target_effect="observation",
        target_entities=query.focus_entity_ids,
        original_query=query.original_query,
        constraints=constraints,
        narrative_style=getattr(world_state, "narrative_style", None),
        preceding_prose=preceding_prose,
        branch_world_id=branch_world_id,
        branch_label=branch_label,
        factual_contrast_summary=factual_contrast_summary,
        # Carry the withheld-information set so the renderer/auditor
        # see the same ``HIDDEN CHANNELS / UTTERANCES (HARD)`` block
        # the directive path enforces. Without this an observation at
        # an early syuzhet_anchor can leak the content of a future
        # utterance via the Rule-1 prose pathway.
        hidden_channels=compute_hidden_channels_for(
            world_state, syuzhet_anchor,
        ),
        rendering=RenderingDirective(
            rendering_mode="observation",
            pov_lock=pov,
            pacing="normal",
            sensory_focus="wide",
            stylistic_instructions=[
                "Ground the prose in concrete physical reality \u2014 what "
                "the POV character sees, hears, touches, and does, "
                "moment by moment.",
                "Render the scene from the focal character's perspective.",
                "Describe what they see, hear, and feel in this moment.",
                "Include environmental details that set the tone.",
                "Ground the prose in the character's current emotional state (use trait values).",
                "Do NOT reveal information the focal character cannot perceive.",
                "Render the scene as the lived present of this world. Do "
                "not stand outside it as a narrator commenting on its "
                "structure.",
            ],
        ),
        scene_context=scene_context,
    )


def _build_exclusion_constraints(
    pruned_utterance_event_ids: Optional[List[str]],
    disabled_channel_ids: Optional[List[str]],
    world_state: WorldStateV1,
    *,
    world_label: str,
) -> List[ConstraintBlock]:
    """Build HARD ConstraintBlocks for utterances/channels the engine
    severed via do-surgery (Rung-2 intervention or Rung-3 counterfactual).

    ``world_label`` is interpolated into the instruction text so the
    renderer sees branch-appropriate wording (e.g. ``"counterfactual"``
    vs ``"intervened"``). The auditor's deterministic withheld-utterance
    check is keyed on ``syuzhet_index`` and does not cover engine-side
    deletion, so without these blocks the renderer reliably re-introduces
    canonical lines that are still present in ``preceding_prose`` /
    ``factual_contrast_summary``.
    """
    blocks: List[ConstraintBlock] = []
    pruned_utts = [u for u in (pruned_utterance_event_ids or []) if u]
    disabled_chs = [c for c in (disabled_channel_ids or []) if c]
    if pruned_utts:
        events_by_id = {e.id: e for e in getattr(world_state, "events", []) or []}
        lines: List[str] = []
        for uid in pruned_utts[:20]:
            evt = events_by_id.get(uid)
            if evt is None:
                lines.append(f"  - {uid}")
                continue
            speaker = getattr(evt, "speaker_id", None) or "unknown"
            addressees = list(getattr(evt, "addressee_ids", []) or [])
            # Anti-pink-elephant: do NOT show ``content`` verbatim. The
            # canonical text is exactly what we are forbidding the
            # renderer to echo, so quoting it in the "do not echo"
            # instruction reliably makes it the most salient phrase
            # in the prompt and the renderer either reproduces it
            # verbatim or paraphrases its evidentiary logic. Show only
            # a *structural fingerprint* — the speech-act shape that
            # is forbidden, not the wording. The id slug
            # (e.g.\u00a0EVT_UTT_GEORGE_ORDERS_KEN_KILL_COADY) carries
            # enough semantic content for the renderer to know which
            # speech act is forbidden without showing it the line.
            target_ids = list(getattr(evt, "target_ids", []) or [])
            truth_value = getattr(evt, "truth_value", None) or ""
            via_channel = getattr(evt, "via_channel_id", None) or ""
            fp_parts: list[str] = []
            if target_ids:
                fp_parts.append(f"about={target_ids}")
            if truth_value:
                fp_parts.append(f"truth={truth_value}")
            if via_channel:
                fp_parts.append(f"via={via_channel}")
            fingerprint = (" | " + ", ".join(fp_parts)) if fp_parts else ""
            lines.append(
                f"  - {uid}: speaker={speaker} \u2192 "
                f"addressees={addressees}{fingerprint}"
            )
        if len(pruned_utts) > 20:
            lines.append(f"  - ...and {len(pruned_utts) - 20} more.")
        blocks.append(ConstraintBlock(
            constraint_type="narrative",
            priority="hard",
            instruction=(
                # Begin with the exact === ERASED UTTERANCES (HARD) ===
                # marker the renderer/auditor prompt files reference,
                # so an LLM that pattern-matches on the heading sees
                # it verbatim, not just the prefix words inside a
                # generic constraints dump.
                f"=== ERASED UTTERANCES (HARD) === \u2014 the speech acts "
                f"identified below were SPOKEN in canon but the do-"
                f"surgery severed their provenance and they DO NOT "
                f"exist in this {world_label} world. The canonical "
                "wording is intentionally NOT shown to you \u2014 only the "
                "speaker, addressees, and topic structure. Do NOT have "
                "any character perform this speech act in any form: "
                "do not echo, paraphrase, remember, or recreate the "
                "evidentiary logic, intent, or causal claim of the "
                "erased line. If the same speaker would naturally "
                "still talk to the same addressee in this scene, "
                "invent a NEW line about a DIFFERENT subject (or a "
                "different evidentiary justification) consistent with "
                "the changed conditions. The auditor will flag both "
                "verbatim quotation and structural paraphrase \u2014 the "
                "act-shape is what is forbidden, not just the wording.\n"
                + "\n".join(lines)
            ),
            evidence={"pruned_utterance_event_ids": pruned_utts},
        ))
    if disabled_chs:
        chs_by_id = getattr(world_state, "channels", {}) or {}
        ch_lines: List[str] = []
        for cid in disabled_chs[:20]:
            ch = chs_by_id.get(cid)
            if ch is None:
                ch_lines.append(f"  - {cid}")
                continue
            medium = getattr(ch, "medium", "?")
            participants = list(getattr(ch, "participant_ids", []) or [])
            ch_lines.append(
                f"  - {cid} ({medium}, participants={participants})"
            )
        if len(disabled_chs) > 20:
            ch_lines.append(f"  - ...and {len(disabled_chs) - 20} more.")
        blocks.append(ConstraintBlock(
            constraint_type="narrative",
            priority="hard",
            instruction=(
                # Same marker-fidelity reasoning as the erased-
                # utterances block above.
                f"=== DISABLED CHANNELS (HARD) === \u2014 these communication "
                f"links existed in canon but the do-surgery removed "
                f"their carrier; they DO NOT exist in this {world_label} "
                "world. Do NOT route any new dialogue or signal "
                "through them, do not refer to them by name, and do "
                "not show characters expecting messages on them.\n"
                + "\n".join(ch_lines)
            ),
            evidence={"disabled_channel_ids": disabled_chs},
        ))
    return blocks


def build_intervention_brief(
    query: InterventionQuery,
    physics_state: Dict[str, Any],
    world_state: WorldStateV1,
    mutations: Optional[List[Dict[str, Any]]] = None,
    blocked: Optional[List[Dict[str, Any]]] = None,
    rule3_pruned_interventions: Optional[List[str]] = None,
    rule2_redundant_evidence: Optional[List[str]] = None,
    rule3_pruning_mode: Literal["advisory", "prune"] = "advisory",
    pruned_utterance_event_ids: Optional[List[str]] = None,
    disabled_channel_ids: Optional[List[str]] = None,
    *,
    preceding_prose: Optional[str] = None,
    branch_world_id: Literal["factual", "shadow"] = "factual",
    branch_label: Optional[str] = None,
    factual_contrast_summary: Optional[str] = None,
    syuzhet_anchor: Optional[int] = None,
) -> CreativeBrief:
    """Build a CreativeBrief for intervention (do-calculus) queries."""
    pruned_set = set(rule3_pruned_interventions or [])
    is_prune_mode = rule3_pruning_mode == "prune"

    # Build InterventionMechanism entries from the interventions dict
    mechanisms: List[InterventionMechanism] = []
    for target_path, new_value in query.interventions.items():
        parts = target_path.split(".", 1)
        node_id = parts[0]
        prop = parts[1] if len(parts) > 1 else "state"

        # Try to find the old state
        old_state = "unknown"
        if node_id in world_state.entities:
            if prop == "status":
                old_state = world_state.entities[node_id].status
            elif prop.startswith("traits."):
                trait_name = prop.split(".", 1)[1]
                tv = world_state.entities[node_id].traits.get(trait_name)
                old_state = f"{tv.value:.2f}" if tv else "unknown"
            elif prop.startswith("relationships."):
                # ``relationships.<other>.<axis>`` — walk social_topology
                # for the per-axis baseline. Without this branch the
                # InterventionMechanism block sent to the rendering LLM
                # and the auditor reports ``old_state="unknown"`` and
                # ``mechanism="physical"`` for any social do-surgery.
                rel_parts = prop.split(".")
                if len(rel_parts) >= 3:
                    other_id = rel_parts[1]
                    axis = rel_parts[2]
                    for rel in world_state.social_topology:
                        if (
                            rel.source_entity_id == node_id
                            and rel.target_entity_id == other_id
                        ):
                            m = rel.metrics.get(axis)
                            if m is not None:
                                old_state = f"{m.value:+.2f}"
                            break
        elif node_id in world_state.objects:
            old_state = world_state.objects[node_id].properties.get(prop, "unknown")

        # Determine mechanism from the property type
        mechanism = "physical"
        if prop.startswith("traits."):
            mechanism = "psychological force overcoming inertia"
        elif prop.startswith("relationships."):
            mechanism = "social pressure overcoming relationship inertia"
        elif prop == "status":
            mechanism = "physical force or environmental change"
        elif prop == "location_id":
            mechanism = "physical movement"

        # Find inertia if applicable
        inertia = 0.5
        if node_id in world_state.entities and prop.startswith("traits."):
            trait_name = prop.split(".", 1)[1]
            tv = world_state.entities[node_id].traits.get(trait_name)
            if tv:
                inertia = tv.inertia
        elif node_id in world_state.entities and prop.startswith("relationships."):
            rel_parts = prop.split(".")
            if len(rel_parts) >= 3:
                other_id = rel_parts[1]
                axis = rel_parts[2]
                for rel in world_state.social_topology:
                    if (
                        rel.source_entity_id == node_id
                        and rel.target_entity_id == other_id
                    ):
                        m = rel.metrics.get(axis)
                        if m is not None:
                            inertia = m.inertia
                        break

        mechanisms.append(InterventionMechanism(
            node_id=node_id,
            old_state=old_state,
            new_state=str(new_value),
            mechanism_hint=mechanism,
            inertia=inertia,
            vacuous=(target_path in pruned_set and is_prune_mode),
            advisory=(target_path in pruned_set and not is_prune_mode),
        ))

    constraints: List[ConstraintBlock] = list(_user_intent_constraints(query.original_query))
    # Scene-internal grounding constraint (mirrors the counterfactual
    # rung). The intervention rung performs do-surgery but the scene is
    # still the actual lived world post-intervention; the renderer must
    # not slip into "what would have happened" subjunctive framing.
    constraints.append(ConstraintBlock(
        constraint_type="narrative",
        priority="hard",
        instruction=(
            "Render this scene as the actual lived world \u2014 concrete "
            "physical action, sensory detail, and character behaviour, "
            "in plain past-tense narration. Do NOT use author-voice "
            "conditional or subjunctive framing (\"if he had\u2026\", "
            "\"would have\u2026\"). The events of this scene are what "
            "actually happened in this world."
        ),
        evidence={},
    ))
    # Blocked propagations become constraints
    if blocked:
        for b in blocked:
            constraints.append(ConstraintBlock(
                constraint_type="spatial",
                priority="hard",
                instruction=(
                    f"BLOCKED: The propagation to {b.get('node_id', '?')}.{b.get('trait', '?')} "
                    f"was blocked by {b.get('reason', 'unknown')}. "
                    f"The state change did NOT propagate — render the resistance."
                ),
                evidence=b,
            ))

    # ctf-calculus pre-flight prunings (Correa & Bareinboim 2025).
    # The engine proved these surgeries vacuous against the user's targets
    # before simulation. The prose MUST NOT invent downstream effects for
    # them — the do-operator was applied locally but is provably
    # disconnected from the rest of the AMWN.
    if rule3_pruned_interventions:
        if rule3_pruning_mode == "prune":
            constraints.append(ConstraintBlock(
                constraint_type="mathematical",
                priority="hard",
                instruction=(
                    "VACUOUS INTERVENTIONS (Rule-3 pruned): "
                    f"{', '.join(rule3_pruned_interventions)}. These surgeries "
                    "have no directed path to any target on the AMWN. Render "
                    "the local change at the intervened node, but do NOT "
                    "describe causal ripples reaching other characters or "
                    "downstream events — the engine proved there are none."
                ),
                evidence={"rule3_pruned": list(rule3_pruned_interventions)},
            ))
        else:
            # Advisory mode: AMWN flagged these as vacuous against the
            # extracted graph, but the engine still ran the surgery
            # because a missed confounder could mask a real causal path.
            # Surface as a SOFT note so the LLM down-weights (but does
            # not suppress) downstream effects.
            constraints.append(ConstraintBlock(
                constraint_type="mathematical",
                priority="soft",
                instruction=(
                    "AMWN ADVISORY (Rule-3): the static causal diagram "
                    "shows no directed path from "
                    f"{', '.join(rule3_pruned_interventions)} to the query "
                    "targets. The do-surgery WAS still applied (advisory "
                    "mode) because the extracted topology may be missing "
                    "latent confounders. Treat downstream consequences "
                    "of these interventions as plausible-but-uncertain; "
                    "prefer subtle echoes over loud causal chains."
                ),
                evidence={"rule3_advisory": list(rule3_pruned_interventions)},
            ))

    constraints.append(ConstraintBlock(
        constraint_type="mathematical",
        priority="hard",
        instruction=(
            "You MUST describe the exact physical mechanism that caused each "
            "state change. Do NOT just say 'the door opened' — render the "
            "physical struggle or action that forced the Impact to overcome "
            "the Inertia. The reader must feel the force required."
        ),
        evidence={},
    ))

    # Channels & beliefs subsystem: the Rung-2 do-surgery can sever
    # downstream utterances and channels (e.g. intervening on a
    # speaker's status removes the lines they would have spoken). The
    # renderer needs to know which canonical lines / links no longer
    # exist in this intervened world; without this block they bleed
    # back in via ``preceding_prose`` / ``factual_contrast_summary``.
    constraints.extend(_build_exclusion_constraints(
        pruned_utterance_event_ids,
        disabled_channel_ids,
        world_state,
        world_label="intervened",
    ))
    # Negative-physics record: prevented events + false propositions.
    constraints.extend(build_prevented_event_constraints(
        world_state, syuzhet_anchor, world_label="intervened",
    ))
    constraints.extend(build_false_proposition_constraints(
        world_state, syuzhet_anchor, world_label="intervened",
    ))

    return CreativeBrief(
        target_effect="intervention",
        target_entities=_entities_from_intervention_keys(
            query.interventions, world_state
        ),
        original_query=query.original_query,
        constraints=constraints,
        narrative_style=getattr(world_state, "narrative_style", None),
        preceding_prose=preceding_prose,
        branch_world_id=branch_world_id,
        branch_label=branch_label,
        factual_contrast_summary=factual_contrast_summary,
        # Surface the engine-authored multi-room split-screen / channel
        # severance text the Rung-2 physics emits on ``physics_state``.
        # Without this lift the renderer/auditor never see the
        # ``=== PHYSICS OVERRIDE (HARD) ===`` block on intervention
        # queries and the engine's per-location override silently
        # vanishes between physics and prose.
        physics_override=(
            physics_state.get("physics_override")
            if isinstance(physics_state, dict) else None
        ),
        # Withheld-utterance / hidden-channel set (see
        # ``build_observation_brief`` for rationale).
        hidden_channels=compute_hidden_channels_for(
            world_state, syuzhet_anchor,
        ),
        rendering=RenderingDirective(
            rendering_mode="intervention",
            pov_lock=(_entities_from_intervention_keys(
                query.interventions, world_state
            ) or [None])[0],
            pacing="normal",
            sensory_focus="normal",
            stylistic_instructions=[
                "Ground the prose in concrete physical reality \u2014 what "
                "the POV character sees, hears, touches, and does, "
                "moment by moment.",
                "Describe the exact physical mechanism for each state change (do-operator).",
                "Render the struggle between Impact and Inertia as physical prose.",
                "Show the cause producing the effect through a specific mechanism "
                "(kinetic, chemical, social, psychological).",
                "If a propagation was blocked, describe the resistance \u2014 the force "
                "that stopped the change from taking hold.",
                "Render the scene as the lived present of this world. Do "
                "not stand outside it as a narrator commenting on its "
                "structure.",
            ],
        ),
        intervention_mechanisms=mechanisms,
        scene_context=(
            {**physics_state, "syuzhet_anchor": syuzhet_anchor}
            if syuzhet_anchor is not None
            and isinstance(physics_state, dict)
            and "syuzhet_anchor" not in physics_state
            else physics_state
        ),
    )


def build_counterfactual_brief(
    query: CounterfactualQuery,
    physics_state: Dict[str, Any],
    world_state: WorldStateV1,
    hidden_deltas: Optional[Dict[str, Dict[str, float]]] = None,
    rule3_pruned_interventions: Optional[List[str]] = None,
    rule2_redundant_evidence: Optional[List[str]] = None,
    rule3_pruning_mode: Literal["advisory", "prune"] = "advisory",
    pruned_utterance_event_ids: Optional[List[str]] = None,
    disabled_channel_ids: Optional[List[str]] = None,
    *,
    preceding_prose: Optional[str] = None,
    branch_world_id: Literal["factual", "shadow"] = "factual",
    branch_label: Optional[str] = None,
    factual_contrast_summary: Optional[str] = None,
    syuzhet_anchor: Optional[int] = None,
) -> CreativeBrief:
    """Build a CreativeBrief for counterfactual (Rung 3) queries."""
    # Build AbductionTruth entries from hidden_deltas.
    #
    # Filter out near-zero deltas (|delta| < 0.10). When the Rung-3
    # propagator hits a cyclic SCC or noisy-OR absorption it returns
    # impact=0.00..0.18 across most traits, which the auditor then
    # flags as "abduction failures" because the prose can't render
    # observable cues for shifts that the simulator itself called
    # negligible. The renderer is asked to invent observable behaviour
    # for an effectively-flat trait distribution — and if it does, the
    # POV-lock auditor flags those exact cues as "diagnostic gloss
    # exceeding perceptual bounds". Dropping near-zero entries here
    # cuts that double-jeopardy at the source. (May 2026 Star Wars
    # counterfactual non-convergence audit.)
    _ABDUCTION_MIN_DELTA = 0.10
    abduction: List[AbductionTruth] = []
    if hidden_deltas:
        skipped_flat = 0
        for entity_id, deltas in hidden_deltas.items():
            for trait, delta_val in deltas.items():
                if abs(float(delta_val)) < _ABDUCTION_MIN_DELTA:
                    skipped_flat += 1
                    continue
                direction = "increased" if delta_val > 0 else "decreased"
                abduction.append(AbductionTruth(
                    entity_id=entity_id,
                    hidden_variable=(
                        f"{trait} {direction} by {abs(delta_val):.2f} "
                        f"(inferred from present-day evidence)"
                    ),
                    weave_hint=(
                        f"Show this through subtle behavioral cues — {entity_id}'s "
                        f"body language, word choice, or micro-reactions should "
                        f"reveal the hidden {trait} shift without exposition."
                    ),
                ))
        if skipped_flat:
            logger.info(
                "[CounterfactualBrief] Skipped %d sub-threshold abduction "
                "shifts (|delta| < %.2f) — propagator likely hit a cyclic "
                "or noisy-OR-absorbed cluster; rendering would be invented "
                "and immediately flagged as POV/abduction conflicts.",
                skipped_flat, _ABDUCTION_MIN_DELTA,
            )

    # Build a counterfactual branch from the intervention keys.
    # Phrasing is scene-internal: the renderer must treat the simulated
    # state as the *actual world* of the scene (Rule 10 / generation
    # Category 3 COUNTERFACTUAL). No "alternate timeline / divergence /
    # branch / what-if" vocabulary leaks into the brief — the renderer
    # echoes brief vocabulary verbatim and the meta-narration auditor
    # then rejects it.
    hist_keys = list(query.historical_interventions.keys())
    cf_branch = CounterfactualBranch(
        actual_outcome="Events as they occurred in the established record.",
        simulated_outcome=(
            f"Events as they unfold under the changed conditions: "
            f"{query.historical_interventions}"
        ),
        divergence_event_id=hist_keys[0].split(".")[0] if hist_keys else None,
    )

    constraints = [
        *_user_intent_constraints(query.original_query),
        ConstraintBlock(
            constraint_type="narrative",
            priority="hard",
            instruction=(
                "Render this scene as the actual lived world — concrete "
                "physical action, sensory detail, and character behaviour, "
                "in plain past-tense narration. Do NOT use author-voice "
                "conditional or subjunctive framing (\"if he had…\", "
                "\"would have…\"). The events of this scene are what "
                "actually happened in this world."
            ),
            evidence={},
        ),
    ]

    if abduction:
        constraints.append(ConstraintBlock(
            constraint_type="mathematical",
            priority="hard",
            instruction=(
                "Abduction background truths have been inferred by the physics "
                "engine. You MUST weave these into the subtext smoothly — through "
                "casual actions, body language, or environmental details. "
                "Do NOT use clunky exposition. The NarrativeAuditor will check "
                "that these hidden variables are structurally present."
            ),
            evidence={},
        ))

    # ctf-calculus pre-flight prunings (Correa & Bareinboim 2025).
    if rule3_pruned_interventions:
        if rule3_pruning_mode == "prune":
            constraints.append(ConstraintBlock(
                constraint_type="mathematical",
                priority="hard",
                instruction=(
                    "VACUOUS HISTORICAL INTERVENTIONS (Rule-3 pruned): "
                    f"{', '.join(rule3_pruned_interventions)}. These do-surgeries "
                    "have no directed path to the present-day evidence on the "
                    "AMWN. The change at the intervened node holds locally, "
                    "but the rest of the world is unchanged — do NOT extend "
                    "new downstream consequences to the broader story."
                ),
                evidence={"rule3_pruned": list(rule3_pruned_interventions)},
            ))
        else:
            constraints.append(ConstraintBlock(
                constraint_type="mathematical",
                priority="soft",
                instruction=(
                    "AMWN ADVISORY (Rule-3): the static causal diagram "
                    "shows no directed path from "
                    f"{', '.join(rule3_pruned_interventions)} to present-"
                    "day evidence. The do-surgery WAS still applied "
                    "(advisory mode); the extracted topology may be "
                    "missing latent confounders. Render downstream "
                    "consequences cautiously — favour atmospheric shifts "
                    "over explicit causal chains."
                ),
                evidence={"rule3_advisory": list(rule3_pruned_interventions)},
            ))
    if rule2_redundant_evidence:
        constraints.append(ConstraintBlock(
            constraint_type="mathematical",
            priority="soft",
            instruction=(
                "REDUNDANT EVIDENCE (Rule-2): "
                f"{', '.join(rule2_redundant_evidence)} are d-separated "
                "from the historical interventions on the AMWN. Their "
                "present-day state did not constrain the abduction — treat "
                "them as background colour, not evidential anchors."
            ),
            evidence={"rule2_redundant": list(rule2_redundant_evidence)},
        ))

    # Surface the present-day evidence the abduction was conditioned on.
    # The auditor / generator otherwise have no idea which observed facts
    # anchored the latent-trait inference, and the prose can drift away
    # from the user's stated grounding.
    evidence_ids = list(getattr(query, "evidence_node_ids", []) or [])
    if evidence_ids:
        constraints.append(ConstraintBlock(
            constraint_type="mathematical",
            priority="hard",
            instruction=(
                "PRESENT-DAY EVIDENCE (abduction was conditioned on these "
                f"node states): {', '.join(evidence_ids)}. The scene must "
                "remain consistent with these observed facts where they are "
                "not directly contradicted by the historical intervention "
                "— they are the anchor that justified the inferred "
                "hidden-variable shifts."
            ),
            evidence={"evidence_node_ids": evidence_ids},
        ))

    # ERASED-BY-DIVERGENCE EXCLUSIONS.
    # The Rung-3 surgery removes utterances and channels whose
    # provenance was severed by the historical intervention. Telling
    # the renderer *what no longer exists* in this counterfactual
    # world is as important as telling it what does — without this
    # block the renderer reliably re-introduces canonical lines
    # ("she said the things she had always said") because they are
    # still present in ``preceding_prose`` / ``factual_contrast``
    # even though the engine deleted them. The auditor's
    # withheld-utterance leak check (which is keyed off
    # ``syuzhet_index``) does not cover deletion, so leaks here
    # appear as silent canon-bleed instead of typed violations.
    constraints.extend(_build_exclusion_constraints(
        pruned_utterance_event_ids,
        disabled_channel_ids,
        world_state,
        world_label="counterfactual",
    ))
    # Negative-physics record: prevented events + false propositions.
    constraints.extend(build_prevented_event_constraints(
        world_state, syuzhet_anchor, world_label="counterfactual",
    ))
    constraints.extend(build_false_proposition_constraints(
        world_state, syuzhet_anchor, world_label="counterfactual",
    ))

    # Resolve target entities from the historical intervention keys
    # (entity props OR event participants) and union with any explicit
    # downstream target nodes the user named.
    target_entities = _entities_from_intervention_keys(
        query.historical_interventions, world_state
    )
    extra_targets = _entities_from_intervention_keys(
        getattr(query, "target_node_ids", []) or [], world_state
    )
    for eid in extra_targets:
        if eid not in target_entities:
            target_entities.append(eid)

    return CreativeBrief(
        target_effect="counterfactual",
        target_entities=target_entities,
        original_query=query.original_query,
        constraints=constraints,
        narrative_style=getattr(world_state, "narrative_style", None),
        preceding_prose=preceding_prose,
        branch_world_id=branch_world_id,
        branch_label=branch_label,
        factual_contrast_summary=factual_contrast_summary,
        # See build_intervention_brief for rationale: the Rung-3
        # physics emits a multi-room override on ``physics_state``
        # that must reach the renderer/auditor brief or it is silently
        # dropped.
        physics_override=(
            physics_state.get("physics_override")
            if isinstance(physics_state, dict) else None
        ),
        # Withheld-utterance / hidden-channel set (see
        # ``build_observation_brief`` for rationale).
        hidden_channels=compute_hidden_channels_for(
            world_state, syuzhet_anchor,
        ),
        rendering=RenderingDirective(
            rendering_mode="counterfactual",
            pov_lock=target_entities[0] if target_entities else None,
            pacing="normal",
            sensory_focus="normal",
            stylistic_instructions=[
                "Ground the prose in concrete physical reality — what the "
                "POV character sees, hears, touches, and does, moment by "
                "moment.",
                "If the changed conditions yield a better outcome than the "
                "established record, let the prose feel cautiously hopeful "
                "— but fragile.",
                "If the changed conditions yield a worse outcome, let the "
                "prose feel eerily wrong.",
                "Weave abduction background truths into character behaviour "
                "naturally — body language, micro-reactions, environmental "
                "detail — never as exposition.",
                "Render the scene as the lived present of this world. Do "
                "not stand outside it as a narrator commenting on its "
                "structure.",
            ],
        ),
        counterfactual_branch=cf_branch,
        abduction_truths=abduction,
        scene_context=(
            {**physics_state, "syuzhet_anchor": syuzhet_anchor}
            if syuzhet_anchor is not None
            and isinstance(physics_state, dict)
            and "syuzhet_anchor" not in physics_state
            else physics_state
        ),
    )


