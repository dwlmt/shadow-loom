def _fmt_traits(traits: Dict[str, Any], *, threshold: float = 0.15) -> str:
    """Render a traits dict as ``name=value`` pairs, skipping near-baseline."""
    parts: List[str] = []
    for tn, td in (traits or {}).items():
        if isinstance(td, dict):
            val = td.get("value", 0.5)
            if abs(val - 0.5) >= threshold:
                parts.append(f"{tn}={val:.2f}")
        elif isinstance(td, (int, float)):
            if abs(float(td) - 0.5) >= threshold:
                parts.append(f"{tn}={float(td):.2f}")
    return ", ".join(parts) if parts else "baseline"


def _fmt_beliefs(beliefs: List[Any], *, max_items: int = 6) -> List[str]:
    out: List[str] = []
    for b in (beliefs or [])[:max_items]:
        if not isinstance(b, dict):
            continue
        target = b.get("target_id", "?")
        state = b.get("perceived_state", "")
        conf = b.get("confidence", 1.0)
        out.append(f"      believes {target}: \"{state}\" (conf={conf:.2f})")
    return out


def _normalise_omniscient_to_ego_shape(
    ctx: Dict[str, Any],
    *,
    recent_event_limit: int = 20,
) -> Dict[str, Any]:
    """Convert a full ``WorldStateV1.model_dump()`` into the ego-graph
    payload shape consumed by :func:`format_scene_context_for_prompt`.

    Rung-1 observation queries that don't pin a POV go through
    :func:`extract_full_world_state`, which returns the whole world as
    a ``WorldStateV1.model_dump()`` (``entities`` is a *dict* keyed by
    id, ``events`` is a list, ``social_topology`` is a list, etc.).
    The ego-graph extractor instead returns lists keyed
    ``focus_entities`` / ``present_entities`` / ``current_locations`` /
    ``recent_memory`` / ... With no shape coercion, the formatter
    silently emits an empty scene context for omniscient observations.

    This helper detects the omniscient shape (``entities`` is a dict
    *and* no ego-graph keys are present) and rewrites it so all
    downstream rendering paths see a uniform structure. Events are
    sliced to the most recent ``recent_event_limit`` (sorted by
    ``fabula_time`` descending) so omniscient prompts don't blow the
    context window on long-running worlds; utterance events are
    additionally split into their own ``relevant_utterance_events``
    bucket so dialogue content surfaces under its own header.
    """
    if not ctx:
        return {}
    has_ego_keys = any(
        k in ctx
        for k in (
            "focus_entities", "present_entities", "current_locations",
            "recent_memory", "relevant_causal_edges", "relevant_relationships",
        )
    )
    if has_ego_keys:
        return ctx
    entities = ctx.get("entities")
    if not isinstance(entities, dict):
        return ctx  # Unknown shape; let the formatter try its best.

    def _to_list_with_id(d: Dict[str, Any] | Any) -> List[Dict[str, Any]]:
        if not isinstance(d, dict):
            return list(d) if d else []
        out: List[Dict[str, Any]] = []
        for k, v in d.items():
            if isinstance(v, dict):
                v = dict(v)  # shallow copy so we don't mutate caller
                v.setdefault("id", k)
                out.append(v)
        return out

    ent_list = _to_list_with_id(entities)
    loc_list = _to_list_with_id(ctx.get("locations") or {})
    obj_list = _to_list_with_id(ctx.get("objects") or {})
    chan_list = _to_list_with_id(ctx.get("channels") or {})
    wt_list = _to_list_with_id(ctx.get("world_traits") or {})

    raw_events = list(ctx.get("events") or [])
    raw_events.sort(
        key=lambda e: (
            e.get("fabula_time") if isinstance(e, dict) else 0
        ) or 0,
        reverse=True,
    )
    bounded = raw_events[:recent_event_limit]
    recent_memory = [e for e in bounded if e.get("event_type") != "utterance"]
    utterances = [e for e in bounded if e.get("event_type") == "utterance"]

    return {
        # Treat every entity as "focus" in the omniscient view so the
        # formatter renders trait/belief blocks rather than the
        # condensed co-present line. Empty present_entities avoids
        # double-listing.
        "focus_entities": ent_list,
        "present_entities": [],
        "current_locations": loc_list,
        "present_objects": obj_list,
        "relevant_relationships": list(ctx.get("social_topology") or []),
        "relevant_causal_edges": list(ctx.get("causal_topology") or []),
        "relevant_spatial_edges": list(ctx.get("spatial_topology") or []),
        "relevant_channels": chan_list,
        "relevant_utterance_events": utterances,
        "recent_memory": recent_memory,
        "world_traits": wt_list,
    }


def _normalise_sandbox_to_ego_shape(ctx: Dict[str, Any]) -> Dict[str, Any]:
    """Convert a ``nx.node_link_data(sandbox)`` payload into ego-graph
    shape so :func:`format_scene_context_for_prompt` surfaces the
    *post-surgery* scene for Rung-2 (intervention) and Rung-3
    (counterfactual) queries.

    Rung-2/3 set ``physics_state = nx.node_link_data(sandbox)`` after
    the Causal Engine mutates the sandbox in place. Without coercion
    the formatter sees ``{"nodes": [...], "links": [...]}`` — none of
    its expected keys — and emits an empty scene context, hiding the
    very ``do``-surgery the renderer needs to describe (and the
    auditor needs to validate against). Reading directly off the
    sandbox guarantees that whatever the engine *actually* changed
    (trait values, statuses, locations, beliefs, social metrics,
    pruned utterances, disabled channels, world-trait shifts) reaches
    the prompt verbatim, not a snapshot of the pre-surgery ego graph.
    """
    if not isinstance(ctx, dict) or "nodes" not in ctx or "links" not in ctx:
        return ctx
    nodes = ctx.get("nodes") or []
    links = ctx.get("links") or []

    focus_entities: List[Dict[str, Any]] = []
    present_objects: List[Dict[str, Any]] = []
    locations: List[Dict[str, Any]] = []
    recent_memory: List[Dict[str, Any]] = []
    utterance_events: List[Dict[str, Any]] = []
    world_traits: List[Dict[str, Any]] = []
    channels: List[Dict[str, Any]] = []

    for n in nodes:
        if not isinstance(n, dict):
            continue
        nt = n.get("node_type")
        # node_link_data may serialise the node id under "id"; the
        # original ego payload also stored it under "id" so they
        # collapse cleanly. Strip the bookkeeping fields we added in
        # ``create_sandbox`` so the formatter doesn't see them.
        node = {k: v for k, v in n.items() if k != "node_type"}
        if nt == "Entity":
            focus_entities.append(node)
        elif nt == "NarrativeObject":
            present_objects.append(node)
        elif nt == "Location":
            locations.append(node)
        elif nt == "EventNode":
            if node.get("event_type") == "utterance":
                utterance_events.append(node)
            else:
                recent_memory.append(node)
        elif nt == "WorldTrait":
            world_traits.append(node)
        elif nt == "Channel":
            channels.append(node)

    # Sort recent events by fabula_time desc so the prompt section
    # leads with the most recent — matches the ego-graph contract.
    recent_memory.sort(
        key=lambda e: (e.get("fabula_time") or 0), reverse=True
    )
    utterance_events.sort(
        key=lambda e: (e.get("fabula_time") or 0), reverse=True
    )

    # Lift relationship and spatial-connection edges back into the
    # list-shaped buckets the formatter expects.
    relationships: List[Dict[str, Any]] = []
    spatial_edges: List[Dict[str, Any]] = []
    causal_edges: List[Dict[str, Any]] = []
    for link in links:
        if not isinstance(link, dict):
            continue
        et = link.get("edge_type")
        # node_link_data emits endpoints under "source"/"target"
        src = link.get("source")
        tgt = link.get("target")
        if et == "relationship":
            rel = dict(link)
            rel.setdefault("source_entity_id", src)
            rel.setdefault("target_entity_id", tgt)
            relationships.append(rel)
        elif et == "connected_to":
            se = dict(link)
            se.setdefault("source_id", src)
            se.setdefault("target_id", tgt)
            spatial_edges.append(se)
        elif et == "causal":
            ce = dict(link)
            ce.setdefault("source_id", src)
            ce.setdefault("target_id", tgt)
            causal_edges.append(ce)

    return {
        "focus_entities": focus_entities,
        "present_entities": [],
        "current_locations": locations,
        "present_objects": present_objects,
        "relevant_relationships": relationships,
        "relevant_causal_edges": causal_edges,
        "relevant_spatial_edges": spatial_edges,
        "relevant_channels": channels,
        "relevant_utterance_events": utterance_events,
        "recent_memory": recent_memory,
        "world_traits": world_traits,
    }


def format_scene_context_for_prompt(
    ctx: Dict[str, Any],
    *,
    recent_events: Optional[int] = None,
    max_beliefs: Optional[int] = None,
    loc_desc_chars: Optional[int] = None,
    obj_desc_chars: Optional[int] = None,
    utterance_chars: Optional[int] = None,
) -> str:
    """Build a rich scene-context block from the full ego-graph payload.

    Surfaces every field that ``extract_ego_graph_from_memory`` returns
    (entities + traits + beliefs + status, co-present entities and
    objects, locations + spatial topology, social relationships,
    standing channels, recent events with actor / target / type /
    timing, on-page utterances with content + truth-value, causal
    edges between in-scene nodes, and world traits) so the renderer
    and the auditor can both see the actual world rather than a
    skeleton of names.

    Accepts three input shapes and normalises them up-front:

      1. The ego-graph payload itself (Rung 1 with POV; directives).
      2. A full ``WorldStateV1.model_dump()`` (Rung 1 omniscient via
         :func:`extract_full_world_state`) — see
         :func:`_normalise_omniscient_to_ego_shape`.
      3. An ``nx.node_link_data(sandbox)`` payload (Rung 2 / Rung 3
         post-surgery) — see :func:`_normalise_sandbox_to_ego_shape`.
         This is what surfaces the *shadow-branch* changes (mutated
         traits, statuses, relationships, pruned utterances, …) so
         the renderer and auditor read the same do-operated world.

    Returned as a single multi-line string suitable for embedding
    under a ``=== SCENE CONTEXT ===`` header.

    The optional keyword arguments control how much context is emitted.
    When ``None``, each defaults to the value from
    ``GenerationSettings`` (read at call time from the live settings).
    """
    if not ctx:
        return "(No scene context available.)"

    _s = _get_settings().generation
    _recent_events = recent_events if recent_events is not None else _s.scene_context_recent_events
    _max_beliefs = max_beliefs if max_beliefs is not None else _s.scene_context_max_beliefs
    _loc_desc = loc_desc_chars if loc_desc_chars is not None else _s.scene_context_loc_desc_chars
    _obj_desc = obj_desc_chars if obj_desc_chars is not None else _s.scene_context_obj_desc_chars
    _utt_chars = utterance_chars if utterance_chars is not None else _s.scene_context_utterance_chars

    ctx = _normalise_sandbox_to_ego_shape(ctx)
    ctx = _normalise_omniscient_to_ego_shape(ctx, recent_event_limit=_recent_events)
    sections: List[str] = []

    # ------------------------------------------------------------
    # Locations + spatial topology
    # ------------------------------------------------------------
    locs = ctx.get("current_locations") or ctx.get("relevant_locations") or []
    if locs:
        sections.append("Locations:")
        for loc in locs:
            lid = loc.get("id", "?")
            lname = loc.get("name", lid)
            parent = loc.get("parent_location_id")
            parent_str = f" [parent: {parent}]" if parent else ""
            sections.append(f"  - {lname} ({lid}){parent_str}")
            desc = (loc.get("description") or "").strip()
            if desc:
                sections.append(f"      {desc[:_loc_desc]}")

    spatial = ctx.get("relevant_spatial_edges") or []
    if spatial:
        sections.append("Spatial layout:")
        for se in spatial:
            src = se.get("source_id", "?")
            tgt = se.get("target_id", "?")
            kind = se.get("connection_type") or se.get("type") or "path"
            arrow = "↔" if se.get("bidirectional", True) else "→"
            # Lock + barrier (so the renderer doesn't write characters
            # walking through a locked door, and the auditor can flag
            # such breaches).
            lock_blob = ""
            if se.get("is_locked"):
                barrier = se.get("barrier_item_id")
                lock_blob = (
                    f" [LOCKED, barrier={barrier}]" if barrier else " [LOCKED]"
                )
            # Lifecycle (only surfaced when non-default — most passages
            # are pre-existing and never destroyed, and the prompt
            # stays compact when those facts are implicit).
            est = se.get("established_at_fabula")
            dest = se.get("destroyed_at_fabula")
            life_bits: list = []
            if isinstance(est, int) and est > 0:
                life_bits.append(f"established@t={est}")
            if isinstance(dest, int):
                life_bits.append(f"destroyed@t={dest}")
            life_blob = f" [{', '.join(life_bits)}]" if life_bits else ""
            sections.append(
                f"  - {src} {arrow} {tgt} ({kind}){lock_blob}{life_blob}"
            )

    # ------------------------------------------------------------
    # Focus entities — full traits, beliefs, status
    # ------------------------------------------------------------
    focus = ctx.get("focus_entities") or []
    if focus:
        sections.append("Focus entities (POV / target):")
        for ent in focus:
            eid = ent.get("id", "?")
            name = ent.get("name", eid)
            loc = ent.get("location_id", "unknown")
            status = ent.get("status", "unknown")
            sections.append(f"  - {name} ({eid}) — {status}, present at {loc}")
            sections.append(f"      traits: {_fmt_traits(ent.get('traits') or {})}")
            sections.extend(_fmt_beliefs(ent.get("beliefs") or [], max_items=_max_beliefs))

    # ------------------------------------------------------------
    # Co-present entities — also need traits / status so the renderer
    # can voice them correctly (previously dropped).
    # ------------------------------------------------------------
    present = ctx.get("present_entities") or []
    if present:
        sections.append("Co-present entities (same room as a focus entity):")
        for ent in present:
            eid = ent.get("id", "?")
            name = ent.get("name", eid)
            loc = ent.get("location_id", "unknown")
            status = ent.get("status", "unknown")
            sections.append(f"  - {name} ({eid}) — {status}, present at {loc}")
            traits_str = _fmt_traits(ent.get("traits") or {})
            if traits_str != "baseline":
                sections.append(f"      traits: {traits_str}")

    # ------------------------------------------------------------
    # Objects in the scene (held or on the floor)
    # ------------------------------------------------------------
    objs = ctx.get("present_objects") or []
    if objs:
        sections.append("Objects in scene:")
        for obj in objs:
            oid = obj.get("id", "?")
            oname = obj.get("name", oid)
            owner = obj.get("owner_id")
            oloc = obj.get("location_id")
            where = f"held by {owner}" if owner else (f"at {oloc}" if oloc else "loose")
            sections.append(f"  - {oname} ({oid}) — {where}")
            desc = (obj.get("description") or "").strip()
            if desc:
                sections.append(f"      {desc[:_obj_desc]}")
            # Affordances — what this object lets characters DO. Without
            # surfacing these the renderer can't reason about a key
            # unlocking a door, a weapon enabling a kill, a vehicle
            # enabling travel, etc., and the auditor can't flag prose
            # that uses an object outside its declared affordances.
            affs = obj.get("affordances") or []
            if affs:
                aff_lines: list = []
                for aff in affs:
                    if not isinstance(aff, dict):
                        continue
                    action = aff.get("action") or "?"
                    target_type = aff.get("target_type") or aff.get("target") or ""
                    requires = aff.get("requires") or aff.get("prerequisites") or []
                    bits = [action]
                    if target_type:
                        bits.append(f"→{target_type}")
                    if requires:
                        bits.append(f"req={requires}")
                    aff_lines.append(" ".join(bits))
                if aff_lines:
                    sections.append(
                        f"      affordances: {'; '.join(aff_lines)}"
                    )

    # ------------------------------------------------------------
    # Social relationships in the scene
    # ------------------------------------------------------------
    rels = ctx.get("relevant_relationships") or []
    if rels:
        sections.append("Relationships (in-scene):")
        for r in rels:
            src = r.get("source_entity_id") or r.get("source_id", "?")
            tgt = r.get("target_entity_id") or r.get("target_id", "?")
            metrics = r.get("metrics") or {}
            metric_parts: List[str] = []
            if isinstance(metrics, dict) and metrics:
                for axis, m in metrics.items():
                    if isinstance(m, dict) and "value" in m:
                        metric_parts.append(f"{axis}={m['value']:+.2f}")
                    elif isinstance(m, (int, float)):
                        metric_parts.append(f"{axis}={float(m):+.2f}")
            else:
                # Legacy flat dict. ``trust`` is intentionally NOT in this
                # tuple: it is not a tracked RelationshipMetric axis (the
                # closed Literal vocabulary is affinity / fear /
                # power_dynamic). If trust matters in a story it lives as
                # an entity trait, not as a relationship metric.
                for axis in ("affinity", "fear", "power_dynamic"):
                    val = r.get(axis)
                    if isinstance(val, (int, float)):
                        metric_parts.append(f"{axis}={float(val):+.2f}")
            metric_str = ", ".join(metric_parts) if metric_parts else "(no observed axes)"
            sections.append(f"  - {src} → {tgt}: {metric_str}")

    # ------------------------------------------------------------
    # Standing comms channels involving the focus entities
    # ------------------------------------------------------------
    chans = ctx.get("relevant_channels") or []
    # Build lookup so the dialogue block below can flag low-intelligibility
    # addressees and surface the channel medium next to each utterance.
    chans_by_id: Dict[str, Dict[str, Any]] = {
        ch.get("id"): ch for ch in chans if ch.get("id")
    }
    if chans:
        sections.append(
            "Available communication channels (use these for new dialogue "
            "that crosses distance, mediation, or encryption):"
        )
        for ch in chans:
            cid = ch.get("id", "?")
            cname = ch.get("name", cid)
            medium = ch.get("medium", "?")
            parts = ch.get("participant_ids") or []
            direction = ch.get("directionality", "duplex")
            intel_map = ch.get("intelligibility") or {}
            # Render only the participants whose intelligibility is
            # explicitly degraded — fully comprehensible defaults stay
            # implicit so the prompt stays compact.
            low_intel = [
                f"{pid}={float(v):.2f}"
                for pid, v in intel_map.items()
                if isinstance(v, (int, float)) and float(v) < 1.0
            ]
            intel_blob = (
                f", intelligibility={{{', '.join(low_intel)}}}"
                if low_intel else ""
            )
            sections.append(
                f"  - {cname} ({cid}) — {medium}, {direction}, "
                f"participants={parts}{intel_blob}"
            )

    # ------------------------------------------------------------
    # Recent events — surface actors / targets / type / timing so the
    # renderer can describe them correctly.
    # ------------------------------------------------------------
    mem = ctx.get("recent_memory") or []
    if mem:
        sections.append("Recent events (most recent first):")
        for evt in mem:
            eid = evt.get("id", "?")
            etype = evt.get("event_type", "event")
            ft = evt.get("fabula_time")
            syu = evt.get("syuzhet_index")
            time_str = []
            if ft is not None:
                time_str.append(f"t={ft}")
            if syu is not None:
                time_str.append(f"syu={syu}")
            time_blob = f"[{', '.join(time_str)}] " if time_str else ""
            actors = evt.get("actor_ids") or []
            targets = evt.get("target_ids") or []
            desc = (evt.get("description") or "").strip()
            sections.append(f"  - {time_blob}{eid} ({etype}): {desc}")
            if actors or targets:
                ats = []
                if actors:
                    ats.append(f"actors={actors}")
                if targets:
                    ats.append(f"targets={targets}")
                sections.append(f"      {' '.join(ats)}")

    # ------------------------------------------------------------
    # On-page utterances — full content + truth-value so the renderer
    # can quote / paraphrase faithfully and the auditor can flag
    # truth_value=false lines that are narrated as fact.
    # ------------------------------------------------------------
    utts = ctx.get("relevant_utterance_events") or []
    if utts:
        sections.append("Recent dialogue (utterances):")
        for u in utts:
            uid = u.get("id", "?")
            speaker = u.get("speaker_id") or (u.get("actor_ids") or ["?"])[0]
            addressees = u.get("addressee_ids") or []
            truth = u.get("truth_value")
            content = (u.get("content") or "").strip()
            desc = (u.get("description") or "").strip()
            ft = u.get("fabula_time")
            time_blob = f"[t={ft}] " if ft is not None else ""
            tv = f" (truth={truth})" if truth else ""
            # Show via_channel_id and (when the channel is known) the
            # medium plus any addressees who can't fully decode it. This
            # is what tells the renderer "Darcy's letter to Elizabeth"
            # vs "Darcy says aloud to Elizabeth", and what tells the
            # auditor an addressee on a low-intelligibility channel
            # should not be portrayed as fully understanding.
            via = u.get("via_channel_id")
            via_blob = ""
            if via:
                ch = chans_by_id.get(via)
                if ch is not None:
                    medium = ch.get("medium", "?")
                    intel_map = ch.get("intelligibility") or {}
                    low = [
                        f"{aid}({float(intel_map[aid]):.2f})"
                        for aid in addressees
                        if isinstance(intel_map.get(aid), (int, float))
                        and float(intel_map[aid]) < 1.0
                    ]
                    low_blob = f", low-intel-for=[{', '.join(low)}]" if low else ""
                    via_blob = f" via {via} [{medium}{low_blob}]"
                else:
                    via_blob = f" via {via}"
            sections.append(
                f"  - {time_blob}{uid} — {speaker} → {addressees}{via_blob}{tv}"
            )
            if desc:
                sections.append(f"      {desc[:_utt_chars]}")
            if content:
                sections.append(f"      content: {content[:_utt_chars]}")

    # ------------------------------------------------------------
    # Causal edges between in-scene nodes
    # ------------------------------------------------------------
    causal = ctx.get("relevant_causal_edges") or []
    if causal:
        sections.append("Causal edges (in-scene):")
        for ce in causal:
            src = ce.get("source_id", "?")
            tgt = ce.get("target_id", "?")
            ctype = ce.get("causality_type") or ce.get("relationship_type") or ce.get("type") or "causes"
            mechanism = ce.get("mechanism")
            evidence = ce.get("evidence_strength")
            strength = ce.get("strength")
            force = ce.get("causal_force")
            # For mutation / mutation_social edges the trait_target +
            # trait_delta carry the actual semantic payload (which trait
            # moves, by how much, and toward whom). Without these the
            # renderer can't tell a guilt-mutation from a fear-mutation.
            trait_target = ce.get("trait_target")
            trait_delta = ce.get("trait_delta")
            counterpart = ce.get("rel_counterpart_id")
            extras: list = []
            if mechanism:
                extras.append(f"mech={mechanism}")
            if evidence:
                extras.append(f"ev={evidence}")
            if isinstance(strength, (int, float)):
                extras.append(f"strength={strength:.2f}")
            elif isinstance(force, (int, float)):
                extras.append(f"force={force:.2f}")
            if trait_target:
                if trait_delta is not None:
                    extras.append(f"{trait_target}{float(trait_delta):+.2f}")
                else:
                    extras.append(f"trait={trait_target}")
            if counterpart:
                extras.append(f"vs {counterpart}")
            extras_blob = f" [{', '.join(extras)}]" if extras else ""
            sections.append(f"  - {src} --{ctype}→ {tgt}{extras_blob}")

    # ------------------------------------------------------------
    # World traits (global structural constraints)
    # ------------------------------------------------------------
    wts = ctx.get("world_traits") or []
    if wts:
        sections.append("World traits:")
        for wt in wts:
            wid = wt.get("id", "?")
            wname = wt.get("name", wid)
            mag = wt.get("magnitude", {})
            mag_val = mag.get("value", 0.5) if isinstance(mag, dict) else 0.5
            domains = ", ".join(wt.get("affected_domains") or [])
            sections.append(
                f"  - {wname} ({wid}) — mag={mag_val:.2f}, domains=[{domains}]"
            )
            desc = (wt.get("description") or "").strip()
            if desc:
                sections.append(f"      {desc[:200]}")

    if not sections:
        return "(No scene context available.)"
    return "\n".join(sections)


# Backward-compat alias — kept private because external callers should
# prefer the public ``format_scene_context_for_prompt`` name.
def _format_scene_context(ctx: Dict[str, Any]) -> str:
    return format_scene_context_for_prompt(ctx)


def assemble_rendering_prompt(
    brief: CreativeBrief,
    query_type: str = "directive",
    physics_state: Optional[Dict[str, Any]] = None,
) -> str:
    """Assemble the full semantic prompt injection from a CreativeBrief.

    This is the "Step 9 → Step 10" bridge: all mathematical constraints,
    rendering directives, and scene context are flattened into a single
    text block that the LLM can consume as a user message.
    """
    sections: List[str] = []

    # === User's Original Request ===
    # Surface the verbatim NL query so the model writes for the human's
    # intent, not just the engine's structured derivation. Hard
    # constraints from the brief still take precedence on conflict.
    if brief.original_query:
        sections.append("=== USER'S ORIGINAL REQUEST (verbatim) ===")
        sections.append(brief.original_query.strip())
        sections.append(
            "Honour the spirit of this request wherever it doesn't "
            "contradict the hard constraints below."
        )
        sections.append("")

    # === Source Style Fidelity ===
    # Match the source text's *form* — a plot-summary seed renders a
    # summary-length passage, a short-story seed renders a scene, etc.
    # The user's original query loosens the band ("in detail"
    # widens; "briefly" tightens) so the same world can answer both
    # quick-look and deep-dive questions without misfiring.
    if brief.narrative_style is not None:
        from shadow_loom.narrative_style import format_narrative_style_block
        sections.append(format_narrative_style_block(
            brief.narrative_style,
            original_query=brief.original_query,
        ))
        sections.append("")

    # === Form-class HARD override (top-of-brief banner) ===
    # When the source format is a summary form (synopsis,
    # plot_summary, outline) or a non-narrative form (news_article,
    # historical_account, etc.) AND the rendering mode is one whose
    # default template pulls toward scenic prose, surface the
    # form-class budget as a HARD banner *before* the rendering
    # directive's mode template can pull the renderer toward scene
    # work. Without this hoist the renderer reliably ignores the
    # form-class on the first pass — the override was previously
    # appended after the rendering directive, where the mode
    # template's "render as a lived scene" language was being read
    # first and winning. The auditor would then catch the
    # ``style_mismatch`` and the refinement loop would converge
    # eventually, but every first-pass render was burnt. Hoisting
    # makes the form-class the frame the rest of the brief is read
    # through.
    _early_form_override = ""
    if (
        brief.narrative_style is not None
        and brief.rendering is not None
    ):
        _early_form_override = _form_class_render_override(
            brief.narrative_style.format,
            brief.rendering.rendering_mode,
        )
    if _early_form_override:
        sections.append(_early_form_override)
        sections.append("")

    # === Story so far (narrative continuity) ===
    # Concatenated prose from prior versions in the current session's
    # lineage so a chain of queries (counterfactual → intervention
    # → observation, etc.) renders prose that is continuous with
    # everything that came before, not just the accumulated world
    # state. Background context only — hard constraints and the
    # SCENE CONTEXT below remain authoritative on conflict.
    # Capped to ``preceding_prose_max_chars`` (tail of the text, i.e.
    # the most recent prose) so long session lineages don't overflow
    # the context window.
    if brief.preceding_prose:
        _pp_max = _get_settings().generation.preceding_prose_max_chars
        _pp = brief.preceding_prose.strip()
        if len(_pp) > _pp_max:
            _pp = "…" + _pp[-_pp_max:]
        sections.append("=== STORY SO FAR (prior prose for continuity) ===")
        sections.append(_pp)
        sections.append(
            "Treat the prose above as established narrative this scene "
            "must continue from. Honour its tone, point-of-view drift, "
            "established facts about characters, and any unresolved "
            "threads. Do NOT contradict events that have already been "
            "narrated. The SCENE CONTEXT and CONSTRAINTS below take "
            "precedence on any conflict with the world state."
        )
        sections.append("")

    # === Header ===
    sections.append(f"=== GENERATION TASK: {brief.target_effect.upper()} ===")
    sections.append(f"Target entities: {', '.join(brief.target_entities)}")
    sections.append("")

    # === Branch context (AMWN shadow vs factual) ===
    # Surfaced only on shadow branches so the renderer can keep the
    # scene in productive contrast with canon. Per Rule 10 in
    # generation.md the renderer must use these fields silently —
    # never echoing 'branch', 'timeline', 'in this branch', or any
    # subjunctive author-voice framing into the prose.
    if brief.branch_world_id == "shadow":
        sections.append("=== BRANCH CONTEXT (background only — do NOT surface in prose) ===")
        sections.append("branch_world_id: shadow")
        if brief.branch_label:
            sections.append(f"branch_label: {brief.branch_label}")
        if brief.factual_contrast_summary:
            sections.append("factual_mainline_at_same_horizon:")
            sections.append(brief.factual_contrast_summary.strip())
        sections.append(
            "Use the contrast above silently to keep this scene divergent "
            "from canon. Render the shadow scene as the actual lived world "
            "in plain past-tense narration. Do NOT name the branch, the "
            "mainline, the contrast, or any meta-structure in the prose "
            "(see Rule 10)."
        )
        sections.append("")

    # === Scene Context ===
    sections.append("=== SCENE CONTEXT ===")
    sections.append(_format_scene_context(brief.scene_context))
    sections.append("")

    # === Mathematical Constraints (the guardrails) ===
    sections.append("=== CONSTRAINTS (Step 9 — Semantic Prompt Injection) ===")
    sections.append(_format_constraints(brief.constraints))
    sections.append("")

    # === Rendering Directive (the stylistic control layer) ===
    if brief.rendering:
        sections.append("=== RENDERING DIRECTIVE (Step 10 — How to write) ===")
        sections.append(_format_rendering_directive(brief.rendering))
        # Form-class override. The COUNTERFACTUAL / OBSERVATION /
        # INTERVENTION mode templates in ``prompts/generation.md`` all
        # default to "render as a lived scene grounded in physical
        # action and sensory detail" \u2014 which directly contradicts
        # the STYLE FIDELITY block when the source format is a summary
        # form (synopsis, plot_summary, outline) or a non-narrative
        # form (news_article, historical_account, etc.). The override
        # is now hoisted to a top-of-brief banner (see
        # ``_early_form_override`` above) so the renderer reads it
        # *before* the mode template can pull it toward scene work.
        # We additionally re-anchor it here so anyone reading the
        # rendering directive sees the same constraint inline rather
        # than scrolling back up — the duplication is intentional and
        # the wording is identical.
        if (
            brief.narrative_style is not None
            and not _early_form_override
        ):
            override = _form_class_render_override(
                brief.narrative_style.format,
                brief.rendering.rendering_mode,
            )
            if override:
                sections.append("")
                sections.append(override)
        elif _early_form_override:
            sections.append("")
            sections.append(
                "(Form-class HARD override applies \u2014 see banner at "
                "the top of this brief. The mode template above must be "
                "filtered through that override; on any conflict, the "
                "form-class budget wins.)"
            )
        sections.append("")

    # === Effect-specific payloads ===
    if brief.threat_proximity:
        sections.append(_format_threat_proximity(brief.threat_proximity))
        sections.append("")

    if brief.surprise_profile:
        sections.append(_format_surprise_profile(brief.surprise_profile))
        sections.append("")

    if brief.irony_profile:
        sections.append(_format_irony_profile(brief.irony_profile))
        sections.append("")

    if brief.mystery_profile:
        sections.append(_format_mystery_profile(brief.mystery_profile))
        sections.append("")

    if brief.fear_profile:
        sections.append(_format_fear_profile(brief.fear_profile))
        sections.append("")

    if brief.joy_profile:
        sections.append(_format_joy_profile(brief.joy_profile))
        sections.append("")

    if brief.regret_profile:
        sections.append(_format_regret_profile(brief.regret_profile))
        sections.append("")

    if brief.grief_profile:
        sections.append(_format_grief_profile(brief.grief_profile))
        sections.append("")

    if brief.rage_profile:
        sections.append(_format_rage_profile(brief.rage_profile))
        sections.append("")

    if brief.love_profile:
        sections.append(_format_love_profile(brief.love_profile))
        sections.append("")

    if brief.counterfactual_branch:
        sections.append(_format_counterfactual(brief.counterfactual_branch))
        sections.append("")

    if brief.causal_attribution:
        sections.append(_format_causal_attribution(brief.causal_attribution))
        sections.append("")

    if brief.entanglement_pairs:
        sections.append(_format_entanglement(brief.entanglement_pairs))
        sections.append("")

    if brief.intervention_mechanisms:
        sections.append(_format_interventions(brief.intervention_mechanisms))
        sections.append("")

    if brief.abduction_truths:
        sections.append(_format_abduction(brief.abduction_truths))
        sections.append("")

    # === Physics Override ===
    if brief.physics_override:
        sections.append(
            f"=== PHYSICS OVERRIDE (HARD \u2014 prose must honour) ===\n"
            f"{brief.physics_override}"
        )
        sections.append("")

    # === Epistemic Gaps (reference data) ===
    if brief.epistemic_gaps:
        sections.append("=== EPISTEMIC STATE (character beliefs vs reality) ===")
        for g in brief.epistemic_gaps:
            sections.append(
                f"  {g.entity_id} re {g.belief_target_id}: "
                f"believes='{g.believed_state}' actual='{g.actual_state}' "
                f"({g.gap_type}, mag={g.gap_magnitude:.2f})"
            )
        sections.append("")

    # === Trait Trajectories (reference data) ===
    if brief.trait_trajectories:
        extreme = [t for t in brief.trait_trajectories if abs(t.current_value - 0.5) >= 0.15]
        if extreme:
            sections.append("=== KEY TRAIT STATES ===")
            for t in extreme:
                sections.append(
                    f"  {t.entity_id}.{t.trait_name} = {t.current_value:.2f} "
                    f"(inertia={t.inertia:.2f}, headroom↑={t.headroom_up:.2f}, headroom↓={t.headroom_down:.2f})"
                )
            sections.append("")

    # === Relationship Tensions (reference data) ===
    if brief.relationship_tensions:
        tense = [r for r in brief.relationship_tensions if r.asymmetry_score > 0.1]
        if tense:
            sections.append("=== RELATIONSHIP TENSIONS ===")
            for r in tense:
                sections.append(
                    f"  {r.source_id}→{r.target_id}: affinity={r.affinity:.2f}, "
                    f"fear={r.fear:.2f}, power_dynamic={r.power_dynamic:.2f} "
                    f"(asymmetry={r.asymmetry_score:.2f})"
                )
            sections.append("")

    # === External Research (background only — never authoritative) ===
    if brief.external_research:
        sections.append(
            "=== EXTERNAL RESEARCH (BACKGROUND CONTEXT — NOT AUTHORITATIVE) ==="
        )
        sections.append(
            "These are pre-fetched real-world snippets relevant to the "
            "scene. Use them only to enrich texture (period detail, "
            "place-feel, vocabulary). Do NOT treat them as canonical "
            "events, character traits, or beliefs in this story. The "
            "world-state above remains the sole source of truth."
        )
        for fact in brief.external_research:
            url = f" [{fact.source_url_primary}]" if fact.source_url_primary else ""
            sections.append(
                f"  - {fact.fact_id} ({fact.confidence}) {fact.topic}: "
                f"{fact.summary}{url}"
            )
        sections.append("")

    # === Narrative Tension (fabula/syuzhet displacement) ===
    # Brief carries per-event withholding/flash-forward markers from
    # ``DirectiveAssembler.compute_narrative_tension``. The renderer
    # uses these to pace reveals: ``withheld_cause`` events should
    # feel pre-loaded with consequence (the reader senses something
    # pending) without being explained on-page; ``upcoming_revelation``
    # events should be foreshadowed without being spoiled. Filtered to
    # the items most likely to fire on the *next* beat — full list is
    # already in the brief log for downstream auditing.
    if brief.narrative_tensions:
        active = [
            t for t in brief.narrative_tensions
            if t.tension_type != "linear"
        ]
        if active:
            sections.append(
                "=== NARRATIVE TENSION (pacing — silent guidance) ==="
            )
            sections.append(
                "These are events whose chronological position differs "
                "from their narrative position. Use them to pace this "
                "beat: hint at withheld causes without explaining them, "
                "and foreshadow upcoming revelations without spoiling "
                "them. Do NOT name 'displacement', 'fabula', 'syuzhet', "
                "'foreshadow' or any meta-structure in the prose."
            )
            for t in active[:8]:
                if t.tension_type == "withheld_cause":
                    sections.append(
                        f"  - WITHHELD: {t.event_id} (already happened "
                        f"at fabula_time={t.fabula_time}, revealed later "
                        f"at syuzhet={t.syuzhet_index}, displacement="
                        f"{t.displacement:+.2f}). Pre-load consequence; "
                        f"do not explain. Description: {t.description}"
                    )
                elif t.tension_type == "upcoming_revelation":
                    sections.append(
                        f"  - UPCOMING: {t.event_id} (shown ahead of its "
                        f"fabula time at syuzhet={t.syuzhet_index}, "
                        f"displacement={t.displacement:+.2f}). "
                        f"Foreshadow lightly; the full beat lands later. "
                        f"Description: {t.description}"
                    )
            if len(active) > 8:
                sections.append(
                    f"  … (+{len(active) - 8} more displacement markers)"
                )
            sections.append("")

    # === Utterance & Channel Fidelity ===
    # Hidden channels (carrier capabilities + future utterances) and
    # on-page utterance metadata (truth_value, intelligibility) impose
    # *fidelity* constraints on the prose:
    #   * Withheld utterance content must NOT be quoted, paraphrased,
    #     or summarised in narration.
    #   * On-page utterances marked truth_value='false' must read as a
    #     known lie within the narrative voice — the narrator must not
    #     assert their content as fact.
    #   * Per-recipient intelligibility < 0.3 means the addressee
    #     could not have understood; the prose must not show
    #     comprehension on their side.
    if brief.hidden_channels:
        sections.append(
            "=== UTTERANCE & CHANNEL FIDELITY (HARD) ==="
        )
        for hc in brief.hidden_channels:
            if hc.kind == "channel":
                sections.append(
                    f"  - HIDDEN CHANNEL {hc.channel_id} ({hc.medium}, "
                    f"participants={hc.participant_ids}): exists in the "
                    f"world but the reader has not yet seen any utterance "
                    f"on it. Do not name it, quote from it, or imply its "
                    f"presence."
                )
            else:
                sections.append(
                    f"  - HIDDEN UTTERANCE {hc.utterance_event_id} "
                    f"({hc.medium} from {hc.speaker_id} to "
                    f"{hc.addressee_ids} at syuzhet="
                    f"{hc.discovered_at_syuzhet}): the message itself "
                    f"comes later in narration order. Do not reveal its "
                    f"content."
                )
        sections.append("")

    sections.append(
        "=== TASK ===\n"
        "Write the prose passage now. Honour ALL hard constraints. "
        "The prose must structurally validate against the mathematical "
        "state described above. The NarrativeAuditor will check that "
        "the rendered text is consistent with the physics."
    )

    return "\n".join(sections)


